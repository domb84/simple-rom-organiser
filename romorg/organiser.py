_NO_LINK_ERRNOS = {errno.EPERM, errno.EXDEV, errno.EMLINK, errno.ENOSYS,
                   getattr(errno, "ENOTSUP", -1), getattr(errno, "EOPNOTSUPP", -1)}


def _unlink_linked(src: Path, dst: Path) -> None:
    """Remove ``src`` after ``dst`` was made as a hard link to it.

    Windows refuses to delete a file with the read-only attribute (common for ROMs unpacked from an archive), and then
    refuses to delete the new link as well: the file would stay under both names. The attribute belongs to the file, not
    to a name, so it is cleared for the delete and set again on the name that stays. Elsewhere this is ``os.unlink``."""
    if os.name != "nt":
        os.unlink(src)
        return
    try:
        os.unlink(src)
        return
    except PermissionError:
        st = os.lstat(src)
        if not st.st_file_attributes & stat.FILE_ATTRIBUTE_READONLY:
            raise
    os.chmod(src, st.st_mode | stat.S_IWRITE)
    try:
        os.unlink(src)
    except OSError:
        try:
            os.unlink(dst)                 # possible now that the attribute is cleared: the file is in one place again
        finally:
            os.chmod(src, st.st_mode)
        raise
    os.chmod(dst, st.st_mode)


def _move_exclusive(src: Path, dst: Path) -> None:
    """Move src -> dst without ever replacing an existing dst.

    Uses ``link`` + ``unlink`` (atomic: fails if dst exists) where hard links are
    supported, else falls back to check-then-rename (FAT/exFAT).
    """
    try:
        os.link(src, dst, follow_symlinks=False)
    except FileExistsError:
        raise FileExistsError(f"target exists: {dst}") from None
    except (NotImplementedError, AttributeError):
        pass
    except OSError as exc:
        if exc.errno not in _NO_LINK_ERRNOS:
            raise
    else:
        try:
            _unlink_linked(src, dst)
        except OSError:
            try:
                os.unlink(dst)
            except OSError:
                pass
            raise
        return
    if _exists(dst):
        raise FileExistsError(f"target exists: {dst}")
    os.rename(src, dst)


def _temp_name(p: Path) -> Path:
    return p.with_name(f"{p.name}{TEMP_MARKER}{uuid.uuid4().hex[:8]}")


def _rename_no_overwrite(src: Path, dst: Path) -> None:
    """Rename src -> dst, refusing to overwrite. Case-only renames use a temp name."""
    if not _exists(src):
        raise FileNotFoundError(f"source missing: {src}")
    if _exists(dst):
        if not _same_file(src, dst):
            raise FileExistsError(f"target exists: {dst}")
        # Case-insensitive FS and only the case differs: go via a temporary name.
        tmp = _temp_name(src)
        os.rename(src, tmp)
        try:
            if _exists(dst) and not _same_file(tmp, dst):
                raise FileExistsError(f"target exists: {dst}")
            _move_exclusive(tmp, dst)
        except BaseException:
            os.rename(tmp, src)
            raise
        return
    _move_exclusive(src, dst)


