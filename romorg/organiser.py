def _restore_from_temp(src: Path) -> bool:
    """A case-only rename / cycle interrupted mid-way leaves ``<name>.romorg-tmp-xxxx``."""
    try:
        hits = [p for p in src.parent.iterdir() if p.name.startswith(src.name + TEMP_MARKER)]
    except OSError:
        return False
    if len(hits) != 1 or _exists(src):
        return False
    try:
        _move_exclusive(hits[0], src)
    except OSError:
        return False
    return True


def _file_matches(path: Path, size: int, sha1: str) -> bool:
    """True when ``path`` is a regular file of ``size`` bytes with this sha1."""
    try:
        if os.stat(path).st_size != size:
            return False
        h = hashlib.sha1()
        with open(path, "rb") as f:
            for chunk in iter(lambda: f.read(1 << 20), b""):
                h.update(chunk)
    except OSError:
        return False
    return h.hexdigest() == sha1.lower()


def undo(log_path: Path, root: Optional[Path] = None) -> dict[str, Any]:
    """Reverse the steps recorded in ``log_path`` (last first).

    Paths come from the log relative to its own folder (old absolute logs are
    rebased), and anything resolving outside that folder is refused. Recreates
    removed directories and deleted playlists, walks the moves and creates in reverse
    (restores moves; deletes files the apply created - e.g. Convert's clean copies -
    only if their size and sha1 are unchanged; result key ``created_removed``), deletes our own
    playlists that the restore made stale, then removes directories the apply
    created if they are empty. The log is renamed to ``*.undone`` when everything
    was restored; otherwise it is rewritten with what is left, so undo can be retried.
    ``root``, if given, must be the log's folder.
    """
    log_path = Path(log_path)
    base = log_path.parent.absolute()
    if root is not None and os.path.realpath(root) != os.path.realpath(base):
        raise ValueError("undo log is not in the selected folder")
    log = read_undo_log(log_path)

    dirs_restored = 0
    for p in sorted(log["removed_dirs"], key=lambda d: len(d.parts)):
        if not _exists(p):
            try:
                p.mkdir(parents=True, exist_ok=True)
                dirs_restored += 1
            except OSError:
                pass

    restored = 0
    created_removed = 0
    skipped: list[dict[str, str]] = []
    failed: list[dict[str, str]] = []
    remaining: list[dict[str, Any]] = []
    gone: set[str] = set()  # dst paths emptied by the restore
    for item in reversed(log["steps"]):
        if item.get("op") == "create":
            path = item["path"]
            info = {"src": "", "dst": str(path)}
            if not _exists(path):
                skipped.append({**info, "reason": "already gone"})
                continue
            if os.path.islink(path) or not _file_matches(path, item["size"], item["sha1"]):
                skipped.append({**info, "reason": "changed since it was created"})
                remaining.append(item)
                continue
            try:
                os.unlink(path)
                created_removed += 1
                gone.add(_fold(path))
            except OSError as exc:
                failed.append({**info, "error": str(exc)})
                remaining.append(item)
            continue
        src, dst = item["src"], item["dst"]
        info = {"src": str(src), "dst": str(dst)}
        if not _exists(dst):
            if _restore_from_temp(src):
                restored += 1
                continue
            reason = "already back in place" if _exists(src) else "moved file no longer exists"
            skipped.append({**info, "reason": reason})
            continue
        if _exists(src) and not _same_file(src, dst):
            skipped.append({**info, "reason": "original path is taken"})
            remaining.append(item)
            continue
        try:
            src.parent.mkdir(parents=True, exist_ok=True)
            _rename_no_overwrite(dst, src)
            restored += 1
            gone.add(_fold(dst))
        except OSError as exc:
            failed.append({**info, "error": str(exc)})
            remaining.append(item)

    from . import m3u  # local import: m3u imports this module

    m3us_restored = 0
    left_deleted: list[dict[str, Any]] = []
    for d in log["deleted"]:
        p, content = d["path"], d["content"]
        if p.suffix.lower() != ".m3u" or not content.startswith(m3u.M3U_MARKER):
            continue
        try:
            p.parent.mkdir(parents=True, exist_ok=True)
            with open(p, "x", encoding="utf-8", errors="surrogateescape", newline="\n") as f:
                f.write(content)
            m3us_restored += 1
        except FileExistsError:
            pass  # a newer playlist is there; keep it
        except OSError:
            left_deleted.append(d)

    # Partial output of an interrupted Convert (its original was restored above).
    temps_removed = 0
    left_temps: list[Path] = []
    for t in log["temp_files"]:
        try:
            if os.path.islink(t) or not t.is_file():
                continue  # gone (moved into place, or cleaned up by the run itself)
            os.unlink(t)
            temps_removed += 1
        except FileNotFoundError:
            pass
        except OSError:
            left_temps.append(t)

    # Our playlists that point at files the restore moved away are stale now.
    m3us_removed = 0
    if gone:
        changed = {_fold(item["path"]) for item in remaining if item.get("op") == "create"}  # user edited them
        for path in m3u.find_m3us(base):
            if _fold(path) in changed:
                continue
            info2 = m3u.read_m3u(path)
            if info2 and info2[0] and any(_fold(e) in gone for e in info2[1]):
                try:
                    os.unlink(path)
                    m3us_removed += 1
                except OSError:
                    pass

    dirs_removed = 0
    left_created: list[Path] = []
    for d in sorted(log["created_dirs"], key=lambda p: len(p.parts), reverse=True):
        try:
            os.rmdir(d)
            dirs_removed += 1
        except FileNotFoundError:
            pass
        except OSError:
            left_created.append(d)

    remaining.reverse()  # back to apply order
    if not remaining and not left_deleted and not left_temps:
        try:
            log_path.rename(log_path.with_name(log_path.name + UNDONE_SUFFIX))
        except OSError:
            pass
    else:
        try:
            _write_log(log_path, base, remaining, [d for d in left_created if _exists(d)], left_deleted,
                       left_temps)
        except (OSError, ValueError):
            pass
    return {"restored": restored, "skipped": skipped, "failed": failed, "remaining": len(remaining),
            "dirs_restored": dirs_restored, "dirs_removed": dirs_removed,
            "m3us_restored": m3us_restored, "m3us_removed": m3us_removed, "rejected": log["rejected"],
            "created_removed": created_removed, "temps_removed": temps_removed}


_LOG_RE = re.compile(re.escape(UNDO_PREFIX) + r".*\.json$")


def count_undo_log(log_path: Path) -> int:
    """How many changes an undo log holds (moves + created files), for display.

    Counts the records without building or checking their paths (``read_undo_log`` does that, and takes seconds on the
    log of a big library); records the real undo would reject as outside the folder are therefore counted too."""
    text = Path(log_path).read_text(encoding="utf-8")
    try:
        data = json.loads(text)
    except ValueError:
        data = None
    if isinstance(data, list):                                          # version 1
        return sum(1 for m in data if isinstance(m, dict))
    if isinstance(data, dict) and "moves" in data and data.get("version", 2) < 3:   # version 2
        return sum(1 for m in data.get("moves", []) if isinstance(m, dict))
    n = 0
    for line in text.splitlines():                                      # version 3: JSON lines
        if '"move"' not in line and '"create"' not in line:
            continue
        try:
            rec = json.loads(line)
        except ValueError:
            continue
        if isinstance(rec, dict) and rec.get("op") in ("move", "create"):
            n += 1
    return n


def list_undo_logs(root: Path) -> list[Path]:
    """Undo logs in ``root`` that have not been undone, newest first."""
    root = Path(root)
    try:
        logs = [p for p in root.iterdir() if p.is_file() and _LOG_RE.match(p.name)]
    except OSError:
        return []

    def key(p: Path) -> tuple[int, str]:
        try:
            return (p.stat().st_mtime_ns, p.name)
        except OSError:
            return (0, p.name)

    return sorted(logs, key=key, reverse=True)


