def _split_ext(name: str) -> tuple[str, str]:
    """Split off the last extension (``"a.b.adf"`` -> ``("a.b", ".adf")``)."""
    dot = name.rfind(".")
    if dot <= 0 or dot == len(name) - 1:
        return name, ""
    return name[:dot], name[dot:]


def _truncate_utf8(text: str, max_bytes: int) -> str:
    encoded = text.encode("utf-8", "surrogateescape")
    if len(encoded) <= max_bytes:
        return text
    return encoded[:max_bytes].decode("utf-8", errors="ignore")


@functools.lru_cache(maxsize=131072)
def safe_filename(name: str) -> str:
    """Return ``name`` made safe for Windows/FAT/exFAT and common Linux filesystems.

    Replaces ``: ? * " < > | \\ /`` and control characters with ``_``, strips
    trailing dots/spaces, guards Windows reserved device names and keeps the
    result within 255 UTF-8 bytes while preserving the extension.
    """
    out = _ILLEGAL_RE.sub("_", name).rstrip(" .")
    if not out:
        return "_"
    stem, ext = _split_ext(out)
    if stem.split(".")[0].upper() in _WINDOWS_RESERVED:
        stem = "_" + stem
    if len((stem + ext).encode("utf-8", "surrogateescape")) > MAX_NAME_BYTES:
        ext_bytes = len(ext.encode("utf-8", "surrogateescape"))
        if ext_bytes >= MAX_NAME_BYTES // 2:  # absurd extension: just cut the whole thing
            stem, ext = stem + ext, ""
            ext_bytes = 0
        stem = _truncate_utf8(stem, MAX_NAME_BYTES - ext_bytes).rstrip(" .") or "_"
    return stem + ext


def dat_folder_name(dat_name: str) -> str:
    """Folder name for a DAT: the DAT name (no version), sanitised."""
    return safe_filename(dat_name)


def canonical_dir(root: Path, dat_name: str, layout: Optional[str] = LAYOUT_PER_DAT) -> Path:
    """Folder matched files of ``dat_name`` belong in: ``root/<DAT folder>`` or ``root`` (flat)."""
    return _canonical_dir_cached(os.fspath(root), dat_name, layout)


@functools.lru_cache(maxsize=4096)
def _canonical_dir_cached(root: str, dat_name: str, layout: Optional[str]) -> Path:
    base = Path(root)           # Paths are immutable: every file of a DAT shares this one
    return base if layout == LAYOUT_FLAT else base / dat_folder_name(dat_name)


def _archive_stem(rom: "Rom") -> str:
    """Archive target stem: the No-Intro set name, else the (TOSEC) game name."""
    return getattr(rom, "set_name", "") or rom.game


def _rom_stem(rom: "Rom") -> str:
    return getattr(rom, "set_name", "") or _split_ext(rom.name)[0]


def _target_name(rom: "Rom", src_name: str, archive_ext: Optional[str] = None,
                 matched_via: str = "raw", byte_order: str = "") -> str:
    """:func:`target_filename` before sanitising."""
    if archive_ext is not None:
        return _archive_stem(rom) + archive_ext
    if matched_via in ("", "raw"):
        return rom.name
    stem = _rom_stem(rom)
    _, rom_ext = _split_ext(rom.name)
    _, src_ext = _split_ext(src_name)
    if matched_via == "byteswapped":
        ext = BYTE_ORDER_EXT.get(byte_order) or src_ext or rom_ext
    elif not src_ext or src_ext.casefold() == rom_ext.casefold():
        # Claims to be clean (or has no extension): the headered variant of the rom's ext.
        ext = HEADERED_EXT.get(rom_ext.casefold(), rom_ext)
    else:
        ext = src_ext
    return stem + ext


def target_filename(rom: "Rom", src_name: str, archive_ext: Optional[str] = None,
                    matched_via: str = "raw", byte_order: str = "") -> str:
    """Canonical filename for a file matching ``rom`` (always :func:`safe_filename`-ed).

    Archive -> ``<archive stem><archive_ext>``; raw match -> ``rom.name``;
    byte-swapped N64 -> ``<stem>.v64`` / ``<stem>.n64`` (by ``byte_order``);
    headerless -> ``<stem><original ext>``, except when the original extension is the
    rom's own (it claims to be clean) or missing -> the headered one (``.sfc`` -> ``.smc``,
    ``.unh`` -> ``.nes``; other extensions unchanged). ``stem`` = the set name, else the
    rom name without its extension. Content is never converted, so the extension stays honest.
    """
    return safe_filename(_target_name(rom, src_name, archive_ext, matched_via, byte_order))


def choose_rom(current: str, roms: Sequence["Rom"], key: Callable[["Rom"], str]) -> tuple["Rom", list["Rom"]]:
    """Pick the rom whose ``key`` best matches ``current``; return (chosen, alternatives).

    Exact (or exact-after-sanitising) name wins, else highest difflib ratio,
    ties broken alphabetically.
    """
    if len(roms) == 1:
        return roms[0], []
    ordered = sorted(roms, key=lambda r: (key(r), r.name))
    chosen: Optional["Rom"] = None
    for r in ordered:
        if key(r) == current or safe_filename(key(r)) == current:
            chosen = r
            break
    if chosen is None:
        best = -1.0
        for r in ordered:
            ratio = difflib.SequenceMatcher(None, current, key(r)).ratio()
            if ratio > best:
                best, chosen = ratio, r
    assert chosen is not None
    return chosen, [r for r in ordered if r is not chosen]


# --------------------------------------------------------------------------- fs helpers
# Small wrappers so tests can simulate a case-insensitive filesystem.


def _exists(p: Path) -> bool:
    return os.path.lexists(p)


def _same_file(a: Path, b: Path) -> bool:
    try:
        return os.path.samefile(a, b)
    except OSError:
        return False


def _same_content(a: Path, b: Path) -> bool:
    try:
        return filecmp.cmp(a, b, shallow=False)
    except OSError:
        return False


def _fold(p: Path) -> str:
    """Case-insensitive key for a path (exFAT/FAT/NTFS/APFS compare names this way)."""
    return os.path.normcase(str(p)).casefold()


def _abs(path: Path, root: Path) -> Path:
    return path if path.is_absolute() else root / path


def _rel_text(path: Path, root: Path) -> Optional[str]:
    """``path`` relative to ``root`` as an os-separated string (None when it is outside; "" for the root itself).
    String work only: this runs for every file of a big scan and pathlib's ``relative_to`` was the planner's hot spot."""
    text, base = os.fspath(path), os.fspath(root)
    if text == base:
        return ""
    if base.endswith(os.sep):                # the filesystem root
        return text[len(base):] if text.startswith(base) else None
    return text[len(base) + 1:] if text.startswith(base + os.sep) else None


def _rel_to(path: Path, root: Path) -> Optional[Path]:
    text = _rel_text(path, root)
    return None if text is None else Path(text)


def _add_reason(op: RenameOp, extra: str) -> None:
    op.reason = f"{op.reason}, {extra}" if op.reason else extra


# --------------------------------------------------------------------------- planning


def _parts_of(path: Path, root: Path) -> tuple[str, ...]:
    text = _rel_text(path, root)
    return tuple(text.split(os.sep)) if text else ()


def _is_reserved_path(path: Path, root: Path) -> bool:
    """True for files inside one of the reserved app folders (:data:`folders.RESERVED_DIRS`)."""
    return folders.classify(_parts_of(path, root)) is not None


def _legacy_folder(path: Path, root: Path) -> Optional[str]:
    """The reserved folder of a file still in the legacy layout (``_unmatched/_excluded/...``), else None."""
    info = folders.classify(_parts_of(path, root))
    return info[0] if info is not None and info[1] else None


def _is_converted_original(path: Path, root: Path) -> bool:
    """True for files under ``_converted_originals/`` (kept by convert.py; also the legacy place)."""
    return folders.is_converted(_parts_of(path, root))


def _is_keep_file(path: Path) -> bool:
    name = path.name.casefold()
    return name in KEEP_NAMES or os.path.splitext(name)[1] in KEEP_SUFFIXES


def _finish_op(src: Path, dst: Path, reasons: list[str], rom_name: str, dat: str,
               unmatched: bool) -> RenameOp:
    at_target = src == dst or (src.name == dst.name and _same_file(src, dst))
    status = "ok" if at_target else "move"
    kind = "rename" if _fold(src.parent) == _fold(dst.parent) else "move"
    if at_target:
        dst = src
    return RenameOp(src, dst, status, ", ".join(reasons), rom_name, kind, dat, unmatched)


def _converted_op(src: Path, root: Path) -> RenameOp:
    """An original kept by Convert stays where it is; one in the legacy place moves to ``_converted_originals/``."""
    if _legacy_folder(src, root) is not None:
        dst = root.joinpath(CONVERTED_DIR, *folders.core_parts(_parts_of(src, root)))
        return RenameOp(src, dst, "move", "original kept by Convert", "", "move", "", True)
    return RenameOp(src, src, "ok", "original kept by Convert", "", "move", "", True)


class _Planner:
    """Per-plan settings for files that matched nothing."""

    def __init__(self, root: Path, missing_dats: Iterable[str],
                 layout: str = LAYOUT_PER_DAT) -> None:
        self.root = root
        self.layout = layout
        # The "folder of a DAT that is not loaded" rule only makes sense with DAT folders.
        self.missing_folders = ({dat_folder_name(n).casefold(): n for n in missing_dats if n}
                                if layout != LAYOUT_FLAT else {})

    def unmatched(self, src: Path, why: str) -> RenameOp:
        root = self.root
        if _is_converted_original(src, root):
            return _converted_op(src, root)
        info = folders.classify(_parts_of(src, root))
        if info is not None:
            name, legacy = info
            if legacy:   # a file in a reason folder of the old layout: the folder moves to the top level
                code = next((c for c, d in CODE_DIRS.items() if d == name), "")
                op = RenameOp(src, root.joinpath(name, *folders.core_parts(_parts_of(src, root))), "move", why,
                              "", "move", "", True)
                op.code = code
                return op
            return RenameOp(src, src, "ok", f"{why}, already in {name}", "", "move", "", True)
        rel = _rel_to(src, root)
        if rel is None:
            return RenameOp(src, src, "skip", "outside the selected folder", "", "move", "", True)
        if len(rel.parts) > 1 and rel.parts[0].casefold() in self.missing_folders:
            dat = self.missing_folders[rel.parts[0].casefold()]
            return RenameOp(src, src, "skip", f"{why}, but the DAT '{dat}' is not loaded - left in its folder",
                            "", "move", "", True)
        if self.layout == LAYOUT_FLAT and len(rel.parts) > 1 and rel.parts[0].casefold() in KEEP_DIRS:
            return RenameOp(src, src, "skip", "frontend media folder - left in place", "", "move", "", True)
        if _is_keep_file(src):
            return RenameOp(src, src, "skip", "frontend / emulator file - left in place", "", "move", "", True)
        return _finish_op(src, root / UNMATCHED_DIR / rel, [why], "", "", True)


def _matched_op(src: Path, root: Path, roms: Sequence["Rom"], archive_ext: Optional[str],
                layout: str = LAYOUT_PER_DAT, matched_via: str = "raw",
                byte_order: str = "") -> tuple[RenameOp, "Rom"]:
    """Op for a loose file (``archive_ext`` None) or a single-game archive, and its rom."""
    if archive_ext is None:
        rom, alts = choose_rom(src.name, roms,
                               key=lambda r: _target_name(r, src.name, None, matched_via, byte_order))
    else:
        stem, _ = _split_ext(src.name)
        rom, alts = choose_rom(stem, roms, key=_archive_stem)
        alts = [r for r in alts if _archive_stem(r) != _archive_stem(rom)]
    target = _target_name(rom, src.name, archive_ext, matched_via, byte_order)
    reasons: list[str] = []
    safe = safe_filename(target)
    if safe != target:
        reasons.append("sanitised for filesystem")
    if matched_via == "headerless":
        reasons.append("matched with its header skipped (file kept as is)")
    elif matched_via == "byteswapped":
        reasons.append(f"matched byte-swapped{f' ({byte_order})' if byte_order else ''} (file kept as is)")
    if alts:
        reasons.append("alternatives: " + "; ".join(r.name for r in alts[:5])
                       + (" ..." if len(alts) > 5 else ""))
    dst = canonical_dir(root, rom.dat, layout) / safe
    return _finish_op(src, dst, reasons, rom.name, rom.dat, False), rom


HEADERLESS_EXTS = {".unh"}  # DAT roms without the header emulators need (NES)


def _header_form(rom: "Rom", matched_via: str) -> str:
    """``"headerless"`` for a file that *is* a headerless dump (raw match of a ``.unh`` rom),
    else ``""``. Latest-only compares versions only within one form, so a newer headerless
    ``.unh`` never sends away the only playable (iNES-headered) copy of a game."""
    if matched_via == "raw" and _split_ext(rom.name)[1].lower() in HEADERLESS_EXTS:
        return "headerless"
    return ""


def reason_destination(src: Path, root: Path, reason_dir: str) -> Path:
    """``root/<reason_dir>/<rel_core>``: ``rel_core`` is the path relative to ``root`` with a leading
    reserved folder (``_unmatched/``, ``_excluded/`` ... or the legacy ``_unmatched/_excluded/``)
    removed. The file name is unchanged, so a file already in another reason folder keeps its place
    in the tree."""
    rel = _rel_to(src, root)
    if rel is None:
        raise ValueError(f"path outside the folder: {src}")
    return root.joinpath(reason_dir, *folders.core_parts(rel.parts))


@dataclass
class MatchedUnit:
    """One matched file the organiser treats as one game: a loose file, or an archive whose members
    all match one game of one DAT (see :func:`matched_units`)."""

    path: Path                 # absolute
    op: RenameOp               # its canonical op (move / ok / conflict later)
    rom: "Rom"                 # the rom chosen by :func:`choose_rom`
    key: frozenset             # {unit_key(rom)} of the primary roms the file stands for
    form: str                  # :func:`_header_form`
    dat: str
    raw: bool                  # exact DAT content (not an alternate-hash match)
    archive: bool
    link: bool                 # symbolic link: never touched
    member: Optional[str] = None
    members: int = 1
    style: str = "tosec"


def _collect(result: "ScanResult", root: Path) -> tuple[dict[Path, "Match"], set[Path],
                                                       dict[Path, list[tuple["Entry", Optional["Match"]]]]]:
    loose_matched: dict[Path, "Match"] = {}
    loose_unmatched: set[Path] = set()
    archives: dict[Path, list[tuple["Entry", Optional["Match"]]]] = {}
    for m in result.matched:
        p = _abs(m.entry.path, root)
        if m.entry.member is None:
            loose_matched.setdefault(p, m)
        else:
            archives.setdefault(p, []).append((m.entry, m))
    for e in result.unmatched:
        p = _abs(e.path, root)
        if e.member is None:
            loose_unmatched.add(p)
        else:
            archives.setdefault(p, []).append((e, None))
    return loose_matched, loose_unmatched, archives


def _scan_units(result: "ScanResult", layout: Optional[str] = None,
                planner: Optional[_Planner] = None) -> tuple[list[MatchedUnit], list[RenameOp]]:
    """``(units, other ops)``; ``other ops`` (unmatched / skipped / converted originals / unsupported /
    unreadable files) are only built when a ``planner`` is given.

    The planner-independent part (the units) is worked out once per scan result and layout and handed out as copies:
    the plan edits its ops, and every preview / total used to rebuild all of them."""
    root = result.root
    if layout is None:
        layout = getattr(result, "layout", LAYOUT_PER_DAT) or LAYOUT_PER_DAT
    units, others, unmatched_loose, unmatched_archives = _base_units(result, layout)
    units = [dataclasses.replace(u, op=copy.copy(u.op)) for u in units]
    others = [copy.copy(o) for o in others]
    if planner is not None:
        for p in unmatched_loose:
            others.append(planner.unmatched(p, "no DAT match"))
        for p, why in unmatched_archives:
            others.append(planner.unmatched(p, why))
        for p in result.unsupported:
            others.append(planner.unmatched(_abs(Path(p), root), "unsupported archive (7z not found)"))
        for p, msg in result.errors:
            ap = _abs(Path(p), root)
            others.append(RenameOp(ap, ap, "skip", f"could not be read: {msg}"))
    return units, others


def _base_units(result: "ScanResult", layout: str) -> tuple[list[MatchedUnit], list[RenameOp], list[Path], list[tuple[Path, str]]]:
    if not getattr(result, "cache_units", False):    # only the server, which never edits a finished scan, opts in
        return _build_units(result, layout)
    cache = result.__dict__.setdefault("_base_units_cache", {})
    if layout not in cache:
        cache[layout] = _build_units(result, layout)
    return cache[layout]


def _build_units(result: "ScanResult", layout: str) -> tuple[list[MatchedUnit], list[RenameOp], list[Path], list[tuple[Path, str]]]:
    from .datfile import unit_key

    root = result.root
    loose_matched, loose_unmatched, archives = _collect(result, root)
    units: list[MatchedUnit] = []
    others: list[RenameOp] = []
    unmatched_archives: list[tuple[Path, str]] = []

    def style_of(rom: "Rom") -> str:
        from .tags import style_of_rom
        return style_of_rom(rom)

    for p, m in loose_matched.items():
        if _is_converted_original(p, root):
            others.append(_converted_op(p, root))
            continue
        via = getattr(m, "matched_via", "raw") or "raw"
        op, rom = _matched_op(p, root, m.primary, None, layout, via, getattr(m, "byte_order", "") or "")
        units.append(MatchedUnit(p, op, rom, frozenset(unit_key(r) for r in m.primary), _header_form(rom, via),
                                 rom.dat, via == "raw", False, os.path.islink(p), None, 1, style_of(rom)))
    unmatched_loose = sorted(loose_unmatched - set(loose_matched), key=os.fspath)

    for p, members in archives.items():
        if _is_converted_original(p, root):
            others.append(_converted_op(p, root))
            continue
        matches = [m for _, m in members if m is not None]
        n = len(members)
        _, ext = _split_ext(p.name)
        if not matches:
            unmatched_archives.append((p, "no DAT match" if n == 1 else f"none of {n} members match"))
            continue
        if len(matches) == n:
            # All members matched: usable if they belong to one game (set) of one DAT.
            dat = matches[0].dat
            games: Optional[set[str]] = None
            for m in matches:
                g = {_archive_stem(r) for r in m.primary} if m.dat == dat else set()
                games = g if games is None else games & g
            if games:
                roms = [r for r in matches[0].primary if _archive_stem(r) in games]
                op, rom = _matched_op(p, root, roms, ext, layout)
                if n > 1:
                    _add_reason(op, f"archive holds {n} roms of one game")
                via = getattr(matches[0], "matched_via", "raw") or "raw"
                key = frozenset(unit_key(r) for m in matches for r in m.primary if _archive_stem(r) in games)
                units.append(MatchedUnit(p, op, rom, key, _header_form(rom, via), rom.dat, via == "raw",
                                         True, os.path.islink(p), members[0][0].member, n, style_of(rom)))
                continue
        others.append(RenameOp(p, p, "skip", f"archive has {n} members ({len(matches)} matched)"))
    return units, others, unmatched_loose, unmatched_archives


def matched_units(result: "ScanResult", layout: Optional[str] = None) -> list[MatchedUnit]:
    """The matched files the organiser treats as one game each (originals kept by Convert excluded).
    :func:`scanner.duplicate_groups` groups these."""
    return _scan_units(result, layout)[0]


def _platform_for(result: "ScanResult", platform: Any = None) -> Any:
    """The platform whose DATs the scan used (``platform`` if given), else a generic stand-in
    where "latest versions" applies to every DAT."""
    if platform is not None:
        return platform
    names = set(getattr(result, "dat_names", ()) or ())
    try:
        from .platforms import list_platforms

        for p in list_platforms():
            if names and names <= set(p.dats):
                return p
    except Exception:  # platforms unavailable: use the stand-in
        pass
    from types import SimpleNamespace

    dats = tuple(getattr(result, "dat_names", ()) or ())
    return SimpleNamespace(name="", dats=dats, latest_dats=dats, best_variant_dats=(), m3u_dats=())


def _send_to_reason(op: RenameOp, root: Path, code: str, why: str, keeper: str = "",
                    missing: tuple[int, ...] = (), flags_text: str = "", superseded_by: str = "",
                    reasons: tuple[str, ...] = ()) -> None:
    """Turn ``op`` into a move to ``<reason dir>/<rel path>`` (``ok`` if it is already there)."""
    reason_dir = CODE_DIRS[code]
    dst = reason_destination(op.src, root, reason_dir)
    new = _finish_op(op.src, dst, [], op.rom_name, op.dat, True)
    op.dst, op.status, op.kind, op.unmatched = new.dst, new.status, new.kind, True
    op.reason = why + (f", already in {reason_dir}" if new.status == "ok" else "")
    op.code, op.keeper, op.missing, op.flags_text, op.superseded_by = code, keeper, tuple(missing), flags_text, superseded_by
    op.reasons = tuple(reasons)


class _Core:
    """Result of one planning run (shared by :func:`plan_renames` and :func:`plan_library`)."""

    def __init__(self, ops: list[RenameOp], selection: Optional["library.Selection"],
                 owners: dict[int, tuple[RenameOp, MatchedUnit]]) -> None:
        self.ops, self.selection, self.owners = ops, selection, owners


def _plan_core(result: "ScanResult", missing_dats: Iterable[str], latest_only: bool,
               layout: Optional[str], profile: Optional["library.LibraryProfile"], platform: Any,
               ratings: Any = None) -> _Core:
    from . import scanner

    root = result.root
    if layout is None:
        layout = getattr(result, "layout", LAYOUT_PER_DAT) or LAYOUT_PER_DAT
    planner = _Planner(root, missing_dats, layout)
    units, others = _scan_units(result, layout, planner)
    ops: list[RenameOp] = [u.op for u in units] + others
    links = {id(u.op) for u in units if u.link}        # the units already know (one lstat per file, done once)
    known = {id(u.op) for u in units}
    for op in ops:
        if op.status in MOVE_STATUSES and (id(op) in links if id(op) in known else os.path.islink(op.src)):
            op.status, op.dst, op.reason = "skip", op.src, "symbolic link - left in place"

    # Duplicates first (independent of the library rules): one keeper per rom, spare copies set aside.
    by_path = {u.path: u for u in units}
    losers: set[Path] = set()
    for keeper, group in scanner.duplicate_groups(result, layout, units=units):
        keeper_rel = _rel_to(keeper, root)
        keeper_text = keeper_rel.as_posix() if keeper_rel is not None else str(keeper)
        for path in group:
            u = by_path.get(path)
            if u is None:
                continue
            losers.add(path)
            _send_to_reason(u.op, root, "duplicate", f"duplicate of {keeper_text}", keeper=keeper_text)

    selection = None
    owners: dict[int, tuple[RenameOp, MatchedUnit]] = {}
    if profile is None and latest_only:
        from . import library

        profile = library.LibraryProfile.latest_only_profile()
    if profile is not None:
        from . import library

        items = []
        have_rom = {(u.dat, u.rom.name) for u in units if not u.link and u.path not in losers}
        for u in units:
            if u.path in losers:
                continue
            if u.link:
                if (u.dat, u.rom.name) in have_rom:
                    continue      # a real file already stands for this rom
                have_rom.add((u.dat, u.rom.name))
            key = len(items)
            owners[key] = (u.op, u)
            items.append(library.Item(key, u.dat, u.rom, u.style, u.path, u.member, u.form, u.link))
        selection = library.select(items, profile, _platform_for(result, platform), ratings=ratings)
        for key, (op, u) in owners.items():
            d = selection.decisions.get(key)
            if d is not None and d.action == library.KEEP and library.BORROWED_CODE in d.codes and not u.link:
                _add_reason(op, d.reason.split("; ")[-1])      # "borrowed as disk N of <set> (...)"
            if d is None or d.action == library.KEEP:
                continue
            code = d.action
            if code not in CODE_DIRS or u.link:
                continue          # a symlink fills slots / ranks like any file but is never moved
            _send_to_reason(op, root, code, d.reason or code, missing=d.missing, flags_text=d.detail,
                            superseded_by=d.superseded_by, reasons=tuple(d.codes))

    ops.sort(key=lambda o: (o.unmatched, o.dat, str(o.src).casefold()))
    _resolve_conflicts(ops, root)
    for op in ops:   # legacy layout: say why the file leaves _unmatched/<reason>/ ; record the target folder
        if op.status in MOVE_STATUSES:
            legacy = _legacy_folder(op.src, root)
            if legacy is not None:
                _add_reason(op, f"moved out of {UNMATCHED_DIR}/{legacy}/ (new layout)")
        op.folder = folders.top_folder(_parts_of(op.dst, root)) or ""
    ops.extend(_plan_m3u_ops(ops, root))
    return _Core(ops, selection, owners)


def plan_renames(result: "ScanResult", missing_dats: Iterable[str] = (),
                 latest_only: bool = False,
                 layout: Optional[str] = None, profile: Optional["library.LibraryProfile"] = None,
                 platform: Any = None) -> list[RenameOp]:
    """Build one op for every file found by the scan (matched, unmatched, unsupported, errors).

    ``missing_dats``: DAT names of the platform that were not loaded; unmatched
    files inside their folders are left alone (``skip``) instead of being swept
    into ``_unmatched/`` (``per_dat`` layout only). Unmatched files are always moved. ``layout`` (``"per_dat"`` | ``"flat"``) defaults to ``result.layout``.
    Files under ``_converted_originals/`` are always left alone (``ok``; the legacy
    ``_unmatched/_converted_originals/`` moves there).
    Our own m3u playlists that reference moving files get a ``delete`` op.

    Spare copies of one rom (same content, loose or archived) go to ``_duplicates/``
    (always; see :func:`scanner.duplicate_groups` for the keeper). With a library ``profile``
    (``latest_only=True`` stands for ``LibraryProfile.latest_only_profile()``) files the profile
    excludes / supersedes / finds incomplete go to ``_excluded/`` / ``_superseded/`` /
    ``_incomplete/`` (``<path relative to root>``, file name unchanged); a file there that no
    longer qualifies moves back to its canonical place. ``platform`` (default: found from the
    scan's DAT names) tells the profile which DATs each rule covers.
    """
    return _plan_core(result, missing_dats, latest_only, layout, profile, platform).ops


def _final_path(op: RenameOp) -> Path:
    return op.dst if (op.status in MOVE_STATUSES or op.status == "ok") else op.src


@dataclass
class LibraryPlan:
    """One preview for "Build library": file moves, playlist writes and removals, and why."""

    ops: list[RenameOp]                  # file moves + ``delete`` ops for stale own playlists
    playlists: list["m3u.M3UOp"]         # write | ok | conflict
    selection: "library.Selection"
    profile: "library.LibraryProfile"

    def counts(self) -> dict[str, int]:
        out = plan_counts(self.ops)
        for k, v in reason_counts(self).items():
            if k.startswith("playlists_"):
                out[k] = v
        return out

    def exclusion_counts(self) -> dict[str, dict[str, int]]:
        """Excluded files per reason code (``library.Selection.exclusion_counts``: ``exclusive`` / ``any``)."""
        return self.selection.exclusion_counts()

    def vanish_summary(self) -> dict:
        """Titles none of whose variants is kept: ``{"titles", "by_reason", "by_code"}``."""
        return self.selection.vanish_summary()

    @property
    def vanished(self) -> list["library.Vanished"]:
        return self.selection.vanished


