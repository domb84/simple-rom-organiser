"""Plan, apply and undo moves that organise a platform folder into DAT folders.

Target layout ``per_dat`` (see docs/ARCHITECTURE.md, Amendment 1; TOSEC platforms)::

    <root>/
      <DAT name>/            one flat folder per DAT (safe_filename(dat name), no version)
      _unmatched/            everything that matched nothing, relative paths preserved

Layout ``flat`` (Amendment 4; No-Intro consoles): matched files live directly in
``<root>/``; ``_unmatched/`` as above. Both layouts may also use the reason folders, all
direct children of ``<root>`` (Amendment 9; see :mod:`folders`, the only list of the names):
``_duplicates/`` (spare copies of one rom), ``_excluded/`` (bad dumps, betas,
demos ... - library profile), ``_superseded/`` (older versions), ``_incomplete/`` (multi-disk
sets with a missing disk), each holding ``<path relative to root>``, and
``_converted_originals/`` (originals kept by "Convert to No-Intro format"; always left where
they are). A file under a reason folder that no longer qualifies for it moves back to its
canonical place (Amendment 6). Files of the legacy layout (``_unmatched/_excluded/...`` etc.)
are recognised as being in that reason folder and move to the top-level one.

Rules:

* Matched loose file -> ``<canonical dir>/<rom.name>``; matched archive with a
  single member -> ``<canonical dir>/<archive stem><ext>`` (the member inside is
  never rewritten; the stem is the No-Intro set name or the TOSEC game name). Files
  matched via an alternate hash (copier header, byte-swapped N64) keep an honest
  extension (``.smc``, ``.v64``, ``.n64``, ``.nes``) - organising never converts content. The DAT is the primary (highest priority) match's DAT. The DAT
  folder is canonical: matched files anywhere under root (incl. ``_unmatched/``)
  are moved there.
* Multi-member archives: moved to the DAT folder only if every member matched and
  they share one game; skipped if only some members match; unmatched otherwise.
* Unmatched files, unsupported archives -> ``<root>/_unmatched/<path relative to
  root>``; files already under ``_unmatched/`` stay where they are. Exceptions
  (status ``skip``): files inside the folder of a DAT that is not loaded, known
  frontend/emulator files (``gamelist.xml``, ``rom.key``, ``*.uae`` ...), symbolic
  links.
* A file whose hash matches several roms (TOSEC duplicates) keeps its name if it
  already equals one of them, else the closest name (``difflib``) wins; ties ->
  alphabetical first.
* Targets go through :func:`safe_filename` (Windows / FAT / exFAT safe names).
* Several local files that are the same rom (same content, same DAT rom, loose or archived):
  one is kept (already canonical, else outside the reserved folders, exact content, loose,
  shortest path, alphabetical) and the others move to ``_duplicates/``.
* Nothing is ever overwritten: moves use ``link`` + ``unlink`` where the
  filesystem supports hard links (atomic no-overwrite), else check-then-rename.
  Duplicates (identical content already at the target) are left in place and
  reported, unless they block another file's canonical name (then they go to
  ``_unmatched/``). Target claims are compared case-insensitively (exFAT SD cards);
  case-only renames and swap cycles go through a temporary name.
* Playlists generated by this app (first line ``# Generated by simple-rom-organiser``)
  that reference files being moved are deleted (status ``delete``; their content
  is kept in the undo log) - write the M3Us again afterwards. User playlists are
  never touched but reported (``skip``) when their disks move.
* After applying, directories that became empty because of our moves are removed
  (never root, DAT folders, ``_unmatched`` or pre-existing empty dirs; emptied reason folders go).
* Every apply journals into ``<root>/.romorg-undo-<timestamp>.json`` *before* each
  step (JSON lines, paths relative to root), so an interrupted apply can still be
  undone. :func:`undo` restores the original paths, refuses anything outside the
  log's folder, and keeps the entries it could not restore for a later retry.
"""

