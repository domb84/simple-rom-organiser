def _make_dirs(directory: Path, created: list[str]) -> None:
    """mkdir -p, recording each directory we actually create (outermost first)."""
    missing: list[Path] = []
    d = directory
    while not _exists(d):
        missing.append(d)
        if d.parent == d:
            break
        d = d.parent
    for d in reversed(missing):
        try:
            os.mkdir(d)
        except FileExistsError:
            continue
        created.append(str(d))


def _protected_dirs(root: Path, ops: Sequence[RenameOp], dat_names: Iterable[str]) -> set[str]:
    names = set(dat_names) | {op.dat for op in ops if op.dat}
    try:
        from .platforms import all_dat_names

        names |= all_dat_names()
    except Exception:  # platforms module unavailable: rely on the explicit names
        pass
    out = {_fold(root), _fold(root / UNMATCHED_DIR)}   # emptied reason folders may go; _unmatched/ stays
    out |= {_fold(root / dat_folder_name(n)) for n in names}
    return out


def _rmdir_empty(d: Path) -> None:
    """``os.rmdir``. On Windows an empty folder with the read-only attribute (Explorer sets it on customised folders) is
    removed too; a folder that is not empty keeps its attribute."""
    try:
        os.rmdir(d)
        return
    except PermissionError:
        if os.name != "nt":
            raise
        st = os.lstat(d)
        if not st.st_file_attributes & stat.FILE_ATTRIBUTE_READONLY:
            raise
    os.chmod(d, st.st_mode | stat.S_IWRITE)
    try:
        os.rmdir(d)
    except OSError:
        os.chmod(d, st.st_mode)
        raise


def _remove_empty_dirs(candidates: Iterable[Path], root: Path, protected: set[str]) -> list[str]:
    """rmdir candidates (and then their parents) that are empty; deepest first."""
    removed: list[str] = []
    todo = sorted({_abs(c, root) for c in candidates}, key=lambda p: len(p.parts), reverse=True)
    for d in todo:
        while _rel_to(d, root) not in (None, Path(".")) and _fold(d) not in protected:
            try:
                _rmdir_empty(d)  # fails unless empty: never removes content
            except OSError:
                break
            removed.append(str(d))
            d = d.parent
    return removed


_is_cancelled = is_cancelled           # (others call it as ``organiser._is_cancelled``)


def _cycle_member(blocked: list[RenameOp]) -> Optional[RenameOp]:
    """A blocked op that is part of a real cycle (A->B, B->A ...), or None."""
    by_src = {_fold(o.src): o for o in blocked}
    for start in blocked:
        seen: set[int] = set()
        cur: Optional[RenameOp] = start
        while cur is not None and id(cur) not in seen:
            seen.add(id(cur))
            cur = by_src.get(_fold(cur.dst))
            if cur is start:
                return start
    return None


def _write_playlist(pl: "m3u.M3UOp", root: Path, written: list[str],
                    failed: list[dict[str, str]], not_moved: Optional[set[str]] = None) -> None:
    """Write one planned playlist (see :func:`apply_renames`); problems go to ``failed``."""
    from . import m3u  # local import: m3u imports this module

    path = pl.path
    info = {"src": str(path), "dst": ""}
    missing = [p for p in m3u.entry_paths(pl.lines, path.parent)
               if not _exists(p) or _fold(p) in (not_moved or ())]
    if missing:
        failed.append({**info, "error": f"disk not at its planned path: {missing[0].name}"})
        return
    text = m3u.content_of(pl.lines)
    existing: Optional[str] = None
    if _exists(path):
        existing = m3u.read_own_m3u_text(path)
        if existing is None:
            failed.append({**info, "error": "a file that is not a playlist of this app exists there"})
            return
    try:
        m3u.write_playlist(path, text, replace_own=existing is not None)
    except (OSError, ValueError) as exc:
        failed.append({**info, "error": str(exc)})
        return
    written.append(str(path))


def all_dirs(root: Path, keep_dirs: Iterable[str] = ()) -> list[Path]:
    """Every folder below ``root``: what the end of a build looks at for empty folders (a clean library: none is left, whoever left
    it). Hidden folders (``.git``, an emulator's ``.cache``) and the system's own folders (``keep_dirs``: Kickstarts ...) are not."""
    keep = {_fold(Path(root) / k) for k in keep_dirs}
    out: list[Path] = []
    for dirpath, dirnames, _files in os.walk(root):
        dirnames[:] = [d for d in dirnames if not d.startswith(".") and _fold(Path(dirpath) / d) not in keep]
        out += [Path(dirpath) / d for d in dirnames]
    return out


def apply_renames(ops: Iterable[RenameOp], root: Path, progress: Optional[ProgressFn] = None,
                  dat_names: Iterable[str] = (), cancel: Any = None,
                  playlists: Sequence["m3u.M3UOp"] = (), keep_dirs: Iterable[str] = ()) -> dict[str, Any]:
    """Perform the ``move`` and ``delete`` ops, then write the ``write`` ``playlists``.

    Returns ``{"moved", "renamed" (same number, legacy key), "deleted", "playlists_written", "failed":
    [{src, dst, error}], "removed_dirs": [..], "cancelled", "error"}``. A playlist whose disks are not all at
    their planned paths (a move failed) is skipped and reported in ``failed``. A move never overwrites: ops blocked
    by a target that another op frees are retried in further passes; swap cycles are broken with a temporary name.
    ``cancel`` (callable or Event) stops between two steps. At the end no empty folder is left below ``root``
    (``keep_dirs``: the system's own folders, never looked at). ``dat_names`` is no longer used.
    """
    root = Path(root)
    all_ops = list(ops)
    moves = [dataclasses.replace(op) for op in all_ops if op.status in MOVE_STATUSES]
    deletes = [op for op in all_ops if op.status == DELETE_STATUS]
    original: dict[int, Path] = {id(op): op.src for op in moves}
    writes = [p for p in playlists if p.status == "write"]
    total = len(moves) + len(deletes) + len(writes)
    written: list[str] = []
    done: list[dict[str, str]] = []
    deleted: list[str] = []
    failed: list[dict[str, str]] = []
    created: list[str] = []
    removed: list[str] = []
    cancelled = False

    def tick(name: str) -> None:
        if progress:
            progress(len(done) + len(deleted) + len(written) + len(failed), total, name)

    pending = moves
    while pending and not cancelled:
        blocked: list[RenameOp] = []
        for op in pending:
            if _is_cancelled(cancel):
                cancelled = True
                break
            if _exists(op.dst) and not _same_file(op.src, op.dst) and _exists(op.src):
                blocked.append(op)
                continue
            try:
                _make_dirs(op.dst.parent, created)
                _rename_no_overwrite(op.src, op.dst)
                done.append({"src": str(original[id(op)]), "dst": str(op.dst)})
            except (OSError, ValueError) as exc:
                failed.append({"src": str(original[id(op)]), "dst": str(op.dst),
                               "error": winproc.long_path_hint(exc, op.src, op.dst)})      # (Windows: paths over 260)
            tick(op.dst.name)
        if cancelled or not blocked:
            break
        if len(blocked) == len(pending):  # no progress: break a swap cycle, or give up
            member = _cycle_member(blocked)
            if member is None:
                for op in blocked:
                    failed.append({"src": str(original[id(op)]), "dst": str(op.dst), "error": "target exists"})
                break
            tmp = _temp_name(member.src)
            try:
                _rename_no_overwrite(member.src, tmp)
                member.src = tmp
            except (OSError, ValueError) as exc:
                blocked.remove(member)
                failed.append({"src": str(original[id(member)]), "dst": str(member.dst), "error": str(exc)})
        pending = blocked
    # A cycle member stuck at its temporary name goes back to where it was.
    for op in moves:
        if op.src != original[id(op)] and _exists(op.src):
            try:
                _rename_no_overwrite(op.src, original[id(op)])
            except (OSError, ValueError):
                pass

    if not cancelled:
        from . import m3u  # local import: m3u imports this module

        for op in deletes:
            if _is_cancelled(cancel):
                cancelled = True
                break
            try:
                if m3u.read_own_m3u_text(op.src) is None:
                    raise ValueError("not a playlist made by simple-rom-organiser")
                os.unlink(op.src)
                deleted.append(str(op.src))
            except (OSError, ValueError) as exc:
                failed.append({"src": str(op.src), "dst": "", "error": str(exc)})
            tick(op.src.name)

    if not cancelled:
        not_moved = {_fold(Path(f["dst"])) for f in failed if f.get("dst")}  # a move that did not happen
        for pl in writes:
            if _is_cancelled(cancel):
                cancelled = True
                break
            _write_playlist(pl, root, written, failed, not_moved)
            tick(pl.path.name)

    # no empty folder stays: not only the ones this run emptied (an empty DAT or _unmatched folder goes too; the system's own
    # folders, keep_dirs, are never looked at)
    protected = {_fold(root)} | {_fold(root / k) for k in keep_dirs}
    sources = ([Path(d["src"]).parent for d in done] + [Path(p).parent for p in deleted]
               + [Path(c) for c in created])
    if not cancelled:
        sources += all_dirs(root, keep_dirs)
    mine = set(created)
    for d in _remove_empty_dirs(sources, root, protected):
        if d not in mine:  # (a folder this apply created and could not fill is no change)
            removed.append(d)
    return {"moved": len(done), "renamed": len(done), "deleted": len(deleted),
            "playlists_written": len(written), "failed": failed,
            "removed_dirs": removed, "cancelled": cancelled, "error": None}


def purge_undo_logs(root: Path) -> int:
    """Delete the undo logs versions before 0.4 left (``<root>/.romorg-undo-*``; Undo is gone): returns how many. Also the data
    folder's undo stores (``undo/``, ``collection-undo/``) once."""
    n = 0
    try:
        for p in Path(root).iterdir():
            if p.is_file() and p.name.startswith(UNDO_PREFIX):
                try:
                    os.unlink(p)
                    n += 1
                except OSError:
                    pass
    except OSError:
        pass
    try:
        import shutil
        from . import paths
        for name in ("undo", "collection-undo"):
            d = paths.data_dir() / name
            if d.is_dir():
                shutil.rmtree(d, ignore_errors=True)
    except Exception:  # noqa: BLE001 - a leftover is harmless
        pass
    return n


LEFTOVER_PART = ".romorg.part"          # a CHD / copy being written (cdconvert, discsys, libexport)
LEFTOVER_UNPACK_DIR = ".romorg-chd-unpack"  # a disc unpacked from its zip / 7z for a conversion (discsys)
LEFTOVER_WHDLOAD = TEMP_MARKER + "whd"  # a WHDLoad game being written (whdbuild)


def recover_leftovers(root: Path, keep_dirs: Iterable[str] = ()) -> dict[str, Any]:
    """Clean up after a run that was killed (Build library calls it first, so no job of this app is running): the partial
    output of a conversion, a CHD, a copy or a WHDLoad game being written is deleted (its original was never touched, or sits in
    ``_converted_originals``); a file left under a temporary name by a move is renamed back. Hidden folders (other than an
    unpack folder of ours) and the system's own folders (``keep_dirs``) are not looked into.

    Returns ``{"deleted": [paths], "renamed": [(from, to)], "left": [{path, reason}], "converts": n}``; ``converts`` counts the
    conversions that were cut short (see :func:`convert.orphan_originals`)."""
    import shutil
    root = Path(root)
    keep = {k.casefold() for k in keep_dirs}
    out: dict[str, Any] = {"deleted": [], "renamed": [], "left": [], "converts": 0}
    for dirpath, dirnames, filenames in os.walk(root):
        here = Path(dirpath)
        for d in list(dirnames):
            if d == LEFTOVER_UNPACK_DIR:
                shutil.rmtree(here / d, ignore_errors=True)
                if not (here / d).exists():
                    out["deleted"].append(str(here / d))
                dirnames.remove(d)
            elif d.startswith(".") or (here == root and d.casefold() in keep):
                dirnames.remove(d)
        for name in filenames:
            p = here / name
            if CONVERT_TEMP_MARKER in name or name.endswith(LEFTOVER_PART) or name.endswith(LEFTOVER_WHDLOAD):
                try:
                    os.unlink(p)
                    out["deleted"].append(str(p))
                    out["converts"] += CONVERT_TEMP_MARKER in name
                except OSError as exc:
                    out["left"].append({"path": str(p), "reason": str(exc)})
            elif TEMP_MARKER in name:
                original = here / name.split(TEMP_MARKER, 1)[0]
                if not name.split(TEMP_MARKER, 1)[0]:
                    continue
                try:
                    _rename_no_overwrite(p, original)
                    out["renamed"].append((str(p), str(original)))
                except (OSError, ValueError) as exc:
                    out["left"].append({"path": str(p), "reason": f"cannot be renamed back to {original.name}: {exc}"})
    return out


class Placement:
    """A converted file put in place of the files it replaces (its sources), shared by every conversion (a cartridge dump, a disc to
    a CHD): :meth:`commit` moves the checked new file to its name, then deletes the sources or keeps each in its new place;
    :meth:`rollback` (after any failure) puts the sources back and takes the new file away again. (Through the public names below,
    which are the seam tests patch.)"""

    def __init__(self, dst: Path, created: list[str]) -> None:
        self.dst = Path(dst)
        self.created = created                      # the folders made so far (the job's), added to by what is kept
        self.placed = False
        self.moved: list[tuple[Path, Path]] = []

    def commit(self, new: Path, op: Any) -> None:
        """``new`` -> ``dst`` (never over a file). Then each ``(source, kept place)`` of ``op.moves`` is deleted (``op.delete_originals``:
        the new file was checked, so from here on it stays whatever happens - a source that cannot be deleted, open elsewhere or
        read-only, is left where it is and reported in ``op.left``; the deleted ones are in ``op.deleted``) or moved to its kept
        place (``op.moves`` stays as it is, for the rollback)."""
        move_exclusive(new, self.dst)
        self.placed = True
        for s, d in list(op.moves):
            if op.delete_originals:
                try:
                    os.unlink(s)
                    op.deleted.append(s)
                except OSError as exc:
                    op.left.append(f"{s}: {exc}")
            else:
                make_dirs(d.parent, self.created)
                rename_no_overwrite(s, d)
                self.moved.append((s, d))
        if op.delete_originals:
            op.moves = []

    def rollback(self) -> None:
        for s, d in list(reversed(self.moved)):
            try:
                rename_no_overwrite(d, s)
                self.moved.remove((s, d))           # back in place: only what could not be restored stays listed
            except (OSError, ValueError):
                pass
        if self.placed and not self.moved:
            try:
                os.unlink(self.dst)
            except OSError:
                pass


def discard_part(path: Path, strict: bool = False) -> None:
    """Remove the half-written ``.part`` file of a conversion (never a link). A leftover of a crashed run is removed before the new one
    is written (``strict``: a file that cannot be removed is an error); what a failed or cancelled run left, afterwards (never an
    error)."""
    try:
        if path.is_file() and not path.is_symlink():
            path.unlink()
    except OSError:
        if strict:
            raise


def tidy_after(root: Path, parents: Iterable[Path], created: Iterable[str], protected: set[str]) -> list[str]:
    """The end of a job that moved or deleted files: the folders it emptied (``parents`` of what it moved) and those it made and left
    empty go. Returns the removed folders that were there before the job (one it made itself is no change)."""
    made = list(created)
    gone = remove_empty_dirs([*parents, *(Path(c) for c in made)], root, protected)
    return [d for d in gone if d not in set(made)]


