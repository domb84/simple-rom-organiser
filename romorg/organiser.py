def _rel_str(path: Path, root: Path) -> str:
    rel = _rel_to(Path(path), root)
    if rel is None or rel == Path("."):
        raise ValueError(f"path outside the folder: {path}")
    return rel.as_posix()


class UndoLogError(RuntimeError):
    """The undo log could not be written: no further changes are made."""


class _Journal:
    """Undo log written as JSON lines *before* each step (opened lazily)."""

    def __init__(self, root: Path) -> None:
        self.root = root
        self.path: Optional[Path] = None
        self._f: Optional[IO[str]] = None
        self._unsynced = 0
        self._seq = 0
        self.useful = False  # True once a recorded step actually happened

    def _open(self) -> None:
        self.path = _new_log_path(self.root)
        try:
            self._f = open(self.path, "x", encoding="utf-8", newline="\n")
        except OSError as exc:
            raise UndoLogError(f"cannot create the undo log: {exc}") from exc
        self._write({"version": LOG_VERSION, "root": str(self.root),
                     "started": datetime.now().isoformat(timespec="seconds")}, sync=True)

    def _write(self, record: dict[str, Any], sync: bool = False) -> None:
        assert self._f is not None
        try:
            self._f.write(json.dumps(record, ensure_ascii=True) + "\n")
            self._f.flush()  # survives a killed process; fsync below covers power loss
            self._unsynced += 1
            if sync or self._unsynced >= FSYNC_EVERY:
                os.fsync(self._f.fileno())
                self._unsynced = 0
        except OSError as exc:
            raise UndoLogError(f"cannot write the undo log: {exc}") from exc

    def record(self, record: dict[str, Any], sync: bool = False) -> int:
        """Append a record; returns its sequence number (for :meth:`failed`)."""
        if self._f is None:
            self._open()
        self._seq += 1
        self._write({**record, "i": self._seq}, sync)
        return self._seq

    def failed(self, seq: int) -> None:
        self._write({"op": "failed", "i": seq})

    def close(self) -> Optional[Path]:
        """Finish the log; remove it if nothing it recorded actually happened."""
        if self._f is None:
            return None
        try:
            self._write({"op": "end"}, sync=True)
        except UndoLogError:
            pass
        finally:
            try:
                self._f.close()
            except OSError:
                pass
            self._f = None
        assert self.path is not None
        if not self.useful:
            try:
                self.path.unlink()
            except OSError:
                pass
            return None
        return self.path


def _new_log_path(root: Path) -> Path:
    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    path = root / f"{UNDO_PREFIX}{stamp}.json"
    n = 1
    while path.exists():
        path = root / f"{UNDO_PREFIX}{stamp}-{n}.json"
        n += 1
    return path


def _inside(path: Path, root: Path, seen: Optional[dict[str, Optional[str]]] = None) -> bool:
    """True when ``path``'s real parent directory lies inside ``root`` (no symlink escapes).

    ``seen``: real paths already resolved during this one read of a log (a log names the same folders thousands of
    times, and resolving walks every path component on disk)."""
    def real(p: Any) -> Optional[str]:
        key = os.fspath(p)
        if seen is None:
            try:
                return os.path.realpath(key)
            except (OSError, ValueError):
                return None
        if key not in seen:
            out: Optional[str]
            parent, name = os.path.split(key)
            try:
                if not name or parent == key:
                    out = os.path.realpath(key)
                else:
                    # resolve the parent first (remembered): then only this one component can still be a link
                    above = real(parent)
                    here = None if above is None else os.path.join(above, name)
                    out = here if here is not None and not os.path.islink(here) else os.path.realpath(key)
            except (OSError, ValueError):
                out = None
            seen[key] = out
        return seen[key]

    real_root, real_parent = real(root), real(os.path.dirname(os.fspath(path)))
    if real_root is None or real_parent is None:
        return False
    return real_parent == real_root or real_parent.startswith(real_root.rstrip(os.sep) + os.sep)


def _resolve_logged(raw: Any, root: Path, old_root: Optional[str],
                    seen: Optional[dict[str, Optional[str]]] = None) -> Optional[Path]:
    """A logged path as an absolute path inside ``root``, or None if it is unsafe.

    Relative paths (v3) resolve against root; absolute ones (v1/v2) are rebased
    from the recorded root (the folder may have been remounted elsewhere).
    """
    if not isinstance(raw, str) or not raw:
        return None
    p = Path(raw)
    if p.is_absolute():
        rel = None
        for base in ([Path(old_root)] if old_root else []) + [root]:
            rel = _rel_to(p, base)
            if rel is not None:
                break
        if rel is None:
            return None
        parts = rel.parts
    else:
        parts = PurePosixPath(raw.replace("\\", "/")).parts
    if not parts or any(part in ("..", "") for part in parts) or Path(*parts).is_absolute():
        return None
    out = root.joinpath(*parts)
    return out if _inside(out, root, seen) else None


def read_undo_log(log_path: Path) -> dict[str, Any]:
    """Parse an undo log (v1 list, v2 JSON document or v3 JSON lines).

    Returns ``{"version", "moves": [{"src": Path, "dst": Path}], "created_files":
    [{"path": Path, "sha1": str, "size": int}], "steps": [...], "created_dirs": [Path],
    "removed_dirs": [Path], "deleted": [{"path": Path, "content": str}], "temp_files": [Path],
    "complete": bool, "rejected": int}``. ``temp_files``: Convert's temporary output files
    (``*.romorg-convert-*``, ``tmp`` records) - left behind only by an interrupted run. ``steps`` holds the move and create records in log order
    (``{"op": "move", "src", "dst"}`` / ``{"op": "create", "path", "sha1", "size"}``);
    ``moves`` is kept for compatibility. Paths are absolute, inside the log's folder;
    entries that would reach outside it are dropped and counted in ``rejected``.
    """
    log_path = Path(log_path)
    root = log_path.parent.absolute()
    seen: dict[str, Optional[str]] = {}       # real paths resolved while reading this log
    text = log_path.read_text(encoding="utf-8")
    records: list[dict[str, Any]] = []
    header: dict[str, Any] = {}
    data: Any = None
    try:
        data = json.loads(text)
    except ValueError:
        data = None
    if isinstance(data, list):  # version 1: plain list of {src, dst}
        header = {"version": 1}
        records = [{"op": "move", **m} for m in data if isinstance(m, dict)]
    elif isinstance(data, dict) and "moves" in data and data.get("version", 2) < 3:
        header = data
        records = [{"op": "move", **m} for m in data.get("moves", []) if isinstance(m, dict)]
        records += [{"op": "mkdir", "path": d} for d in data.get("created_dirs", [])]
        records += [{"op": "rmdir", "path": d} for d in data.get("removed_dirs", [])]
        records.append({"op": "end"})
    else:  # version 3: JSON lines, header first; a torn last line is ignored
        for n, line in enumerate(text.splitlines()):
            try:
                rec = json.loads(line)
            except ValueError:
                continue
            if not isinstance(rec, dict):
                continue
            if n == 0 and "op" not in rec:
                header = rec
            else:
                records.append(rec)
    old_root = header.get("root") if isinstance(header.get("root"), str) else None
    failed = {r.get("i") for r in records if r.get("op") == "failed"}

    out: dict[str, Any] = {"version": header.get("version", LOG_VERSION), "moves": [], "created_files": [],
                           "steps": [], "created_dirs": [], "removed_dirs": [], "deleted": [],
                           "temp_files": [], "complete": False, "rejected": 0}
    created: dict[str, Path] = {}
    for rec in records:
        op = rec.get("op")
        if op == "end":
            out["complete"] = True
            continue
        if op == "failed" or ("i" in rec and rec["i"] in failed):
            continue
        if op == "move":
            src, dst = _resolve_logged(rec.get("src"), root, old_root, seen), _resolve_logged(rec.get("dst"), root, old_root, seen)
            if src is None or dst is None:
                out["rejected"] += 1
            else:
                out["moves"].append({"src": src, "dst": dst})
                out["steps"].append({"op": "move", "src": src, "dst": dst})
        elif op == "create":
            p = _resolve_logged(rec.get("path"), root, old_root, seen)
            sha1, size = rec.get("sha1"), rec.get("size")
            if (p is None or not isinstance(sha1, str) or not sha1
                    or not isinstance(size, int) or isinstance(size, bool)):
                out["rejected"] += 1
            else:
                item = {"path": p, "sha1": sha1.lower(), "size": size}
                out["created_files"].append(item)
                out["steps"].append({"op": "create", **item})
        elif op == "tmp":  # a temporary file Convert was about to write
            p = _resolve_logged(rec.get("path"), root, old_root, seen)
            if p is None or CONVERT_TEMP_MARKER not in p.name:
                out["rejected"] += 1
            else:
                out["temp_files"].append(p)
        elif op in ("mkdir", "unmkdir", "rmdir"):
            p = _resolve_logged(rec.get("path"), root, old_root, seen)
            if p is None:
                out["rejected"] += 1
            elif op == "mkdir":
                created[_fold(p)] = p
            elif op == "unmkdir":
                created.pop(_fold(p), None)
            else:
                out["removed_dirs"].append(p)
        elif op == "delete":
            p = _resolve_logged(rec.get("path"), root, old_root, seen)
            content = rec.get("content")
            if p is None or not isinstance(content, str):
                out["rejected"] += 1
            else:
                out["deleted"].append({"path": p, "content": content})
    out["created_dirs"] = list(created.values())
    return out


def _write_log(log_path: Path, root: Path, steps: list[dict[str, Any]], created: list[Path],
               deleted: list[dict[str, Any]], temps: Sequence[Path] = ()) -> None:
    """Rewrite a log atomically (v3) with what is still left to undo.

    ``steps``: remaining moves (``{"src", "dst"}``, optional ``"op": "move"``) and creates
    (``{"op": "create", "path", "sha1", "size"}``) in apply order.
    """
    lines = [json.dumps({"version": LOG_VERSION, "root": str(root),
                         "started": datetime.now().isoformat(timespec="seconds"), "partial": True})]
    for d in created:
        lines.append(json.dumps({"op": "mkdir", "path": _rel_str(d, root)}))
    for t in temps:
        lines.append(json.dumps({"op": "tmp", "path": _rel_str(t, root)}))
    for m in steps:
        if m.get("op") == "create":
            lines.append(json.dumps({"op": "create", "path": _rel_str(m["path"], root),
                                     "sha1": m["sha1"], "size": m["size"]}))
        else:
            lines.append(json.dumps({"op": "move", "src": _rel_str(m["src"], root),
                                     "dst": _rel_str(m["dst"], root)}))
    for d in deleted:
        lines.append(json.dumps({"op": "delete", "path": _rel_str(d["path"], root), "content": d["content"]}))
    lines.append(json.dumps({"op": "end"}))
    tmp = log_path.with_name(log_path.name + ".tmp")
    with open(tmp, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
        f.flush()
        os.fsync(f.fileno())
    os.replace(tmp, log_path)


