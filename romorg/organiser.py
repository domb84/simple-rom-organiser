def _make_dirs(directory: Path, created: list[str], journal: Optional[_Journal] = None) -> None:
    """mkdir -p, recording each directory we actually create (outermost first)."""
    missing: list[Path] = []
    d = directory
    while not _exists(d):
        missing.append(d)
        if d.parent == d:
            break
        d = d.parent
    for d in reversed(missing):
        try:
            os.mkdir(d)
        except FileExistsError:
            continue
        created.append(str(d))
        if journal is not None:
            journal.record({"op": "mkdir", "path": _rel_str(d, journal.root)})


def _protected_dirs(root: Path, ops: Sequence[RenameOp], dat_names: Iterable[str]) -> set[str]:
    names = set(dat_names) | {op.dat for op in ops if op.dat}
    try:
        from .platforms import all_dat_names

        names |= all_dat_names()
    except Exception:  # platforms module unavailable: rely on the explicit names
        pass
    out = {_fold(root), _fold(root / UNMATCHED_DIR)}   # emptied reason folders may go; _unmatched/ stays
    out |= {_fold(root / dat_folder_name(n)) for n in names}
    return out


def _remove_empty_dirs(candidates: Iterable[Path], root: Path, protected: set[str]) -> list[str]:
    """rmdir candidates (and then their parents) that are empty; deepest first."""
    removed: list[str] = []
    todo = sorted({_abs(c, root) for c in candidates}, key=lambda p: len(p.parts), reverse=True)
    for d in todo:
        while _rel_to(d, root) not in (None, Path(".")) and _fold(d) not in protected:
            try:
                os.rmdir(d)  # fails unless empty: never removes content
            except OSError:
                break
            removed.append(str(d))
            d = d.parent
    return removed


def _is_cancelled(cancel: Any) -> bool:
    if cancel is None:
        return False
    if hasattr(cancel, "is_set"):
        return bool(cancel.is_set())
    return bool(cancel())


def _cycle_member(blocked: list[RenameOp]) -> Optional[RenameOp]:
    """A blocked op that is part of a real cycle (A->B, B->A ...), or None."""
    by_src = {_fold(o.src): o for o in blocked}
    for start in blocked:
        seen: set[int] = set()
        cur: Optional[RenameOp] = start
        while cur is not None and id(cur) not in seen:
            seen.add(id(cur))
            cur = by_src.get(_fold(cur.dst))
            if cur is start:
                return start
    return None


def _write_playlist(pl: "m3u.M3UOp", root: Path, journal: _Journal, written: list[str],
                    failed: list[dict[str, str]], not_moved: Optional[set[str]] = None) -> None:
    """Write one planned playlist (see :func:`apply_renames`); problems go to ``failed``."""
    from . import m3u  # local import: m3u imports this module

    path = pl.path
    info = {"src": str(path), "dst": ""}
    missing = [p for p in m3u.entry_paths(pl.lines, path.parent)
               if not _exists(p) or _fold(p) in (not_moved or ())]
    if missing:
        failed.append({**info, "error": f"disk not at its planned path: {missing[0].name}"})
        return
    text = m3u.content_of(pl.lines)
    data = text.encode("utf-8", errors="surrogateescape")
    existing: Optional[str] = None
    if _exists(path):
        existing = m3u.read_own_m3u_text(path)
        if existing is None:
            failed.append({**info, "error": "a file that is not a playlist of this app exists there"})
            return
    dseq = None
    if existing is not None:
        dseq = journal.record({"op": "delete", "path": _rel_str(path, root), "content": existing})
    cseq = journal.record({"op": "create", "path": _rel_str(path, root),
                           "sha1": hashlib.sha1(data).hexdigest(), "size": len(data)}, sync=True)
    try:
        m3u.write_playlist(path, text, replace_own=existing is not None)
    except (OSError, ValueError) as exc:
        journal.failed(cseq)
        if dseq is not None:
            journal.failed(dseq)
        failed.append({**info, "error": str(exc)})
        return
    journal.useful = True
    written.append(str(path))


def apply_renames(ops: Iterable[RenameOp], root: Path, progress: Optional[ProgressFn] = None,
                  dat_names: Iterable[str] = (), cancel: Any = None,
                  playlists: Sequence["m3u.M3UOp"] = ()) -> dict[str, Any]:
    """Perform the ``move`` and ``delete`` ops, then write the ``write`` ``playlists``.

    Returns ``{"moved", "renamed" (same number, legacy key), "deleted", "playlists_written", "failed":
    [{src, dst, error}], "removed_dirs": [..], "undo_log": path|None, "cancelled"}``.
    Playlists go in the same journal: an existing own file is journalled as ``delete`` (its content)
    first, then a ``create`` record (sha1 + size) *before* the file is written, so one undo removes
    what was created and restores what was replaced. A playlist whose disks are not all at their
    planned paths (a move failed) is skipped and reported in ``failed``.
    Every step is journalled before it happens. Ops blocked by a target that another
    op frees are retried in further passes; swap cycles are broken with a temporary
    name. ``cancel`` (callable or Event) stops between two steps. ``dat_names`` adds
    DAT folders that must never be removed (all known platform DATs are protected anyway).
    """
    root = Path(root)
    all_ops = list(ops)
    moves = [dataclasses.replace(op) for op in all_ops if op.status in MOVE_STATUSES]
    deletes = [op for op in all_ops if op.status == DELETE_STATUS]
    original: dict[int, Path] = {id(op): op.src for op in moves}
    writes = [p for p in playlists if p.status == "write"]
    total = len(moves) + len(deletes) + len(writes)
    journal = _Journal(root)
    written: list[str] = []
    done: list[dict[str, str]] = []
    deleted: list[str] = []
    failed: list[dict[str, str]] = []
    created: list[str] = []
    removed: list[str] = []
    cancelled = False

    def tick(name: str) -> None:
        if progress:
            progress(len(done) + len(deleted) + len(written) + len(failed), total, name)

    def move(op: RenameOp, src: Path, dst: Path) -> None:
        seq = journal.record({"op": "move", "src": _rel_str(src, root), "dst": _rel_str(dst, root)})
        try:
            _rename_no_overwrite(src, dst)
        except BaseException:
            journal.failed(seq)
            raise
        journal.useful = True

    error: Optional[str] = None
    try:
        pending = moves
        while pending and not cancelled:
            blocked: list[RenameOp] = []
            for op in pending:
                if _is_cancelled(cancel):
                    cancelled = True
                    break
                if _exists(op.dst) and not _same_file(op.src, op.dst) and _exists(op.src):
                    blocked.append(op)
                    continue
                try:
                    _make_dirs(op.dst.parent, created, journal)
                    move(op, op.src, op.dst)
                    done.append({"src": str(original[id(op)]), "dst": str(op.dst)})
                except UndoLogError:
                    raise
                except (OSError, ValueError) as exc:
                    failed.append({"src": str(original[id(op)]), "dst": str(op.dst), "error": str(exc)})
                tick(op.dst.name)
            if cancelled or not blocked:
                break
            if len(blocked) == len(pending):  # no progress: break a swap cycle, or give up
                member = _cycle_member(blocked)
                if member is None:
                    for op in blocked:
                        failed.append({"src": str(original[id(op)]), "dst": str(op.dst), "error": "target exists"})
                    break
                tmp = _temp_name(member.src)
                try:
                    move(member, member.src, tmp)
                    member.src = tmp
                except UndoLogError:
                    raise
                except (OSError, ValueError) as exc:
                    blocked.remove(member)
                    failed.append({"src": str(original[id(member)]), "dst": str(member.dst), "error": str(exc)})
            pending = blocked
        # A cycle member stuck at its temporary name goes back to where it was.
        for op in moves:
            if op.src != original[id(op)] and _exists(op.src):
                try:
                    move(op, op.src, original[id(op)])
                except (OSError, ValueError, UndoLogError):
                    pass

        if not cancelled:
            from . import m3u  # local import: m3u imports this module

            for op in deletes:
                if _is_cancelled(cancel):
                    cancelled = True
                    break
                try:
                    content = m3u.read_own_m3u_text(op.src)
                    if content is None:
                        raise ValueError("not a playlist made by simple-rom-organiser")
                    seq = journal.record({"op": "delete", "path": _rel_str(op.src, root), "content": content})
                    try:
                        os.unlink(op.src)
                    except BaseException:
                        journal.failed(seq)
                        raise
                    journal.useful = True
                    deleted.append(str(op.src))
                except UndoLogError:
                    raise
                except (OSError, ValueError) as exc:
                    failed.append({"src": str(op.src), "dst": "", "error": str(exc)})
                tick(op.src.name)

        if not cancelled:
            not_moved = {_fold(Path(f["dst"])) for f in failed if f.get("dst")}  # a move that did not happen
            for pl in writes:
                if _is_cancelled(cancel):
                    cancelled = True
                    break
                _write_playlist(pl, root, journal, written, failed, not_moved)
                tick(pl.path.name)

        protected = _protected_dirs(root, all_ops, dat_names)
        sources = ([Path(d["src"]).parent for d in done] + [Path(p).parent for p in deleted]
                   + [Path(c) for c in created])
        mine = set(created)
        for d in _remove_empty_dirs(sources, root, protected):
            if d in mine:  # a folder this apply created (move failed): not part of the old tree
                created.remove(d)
                mine.discard(d)
                journal.record({"op": "unmkdir", "path": _rel_str(Path(d), root)})
            else:
                journal.record({"op": "rmdir", "path": _rel_str(Path(d), root)})
                journal.useful = True
                removed.append(d)
    except UndoLogError as exc:  # stop: every change made so far is in the log
        error = str(exc)
    finally:
        log_path = journal.close()
    return {"moved": len(done), "renamed": len(done), "deleted": len(deleted),
            "playlists_written": len(written), "failed": failed,
            "removed_dirs": removed, "undo_log": str(log_path) if log_path else None,
            "cancelled": cancelled, "error": error}


