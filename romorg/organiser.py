@dataclass
class RenameOp:
    src: Path
    dst: Path
    status: str  # move | ok | conflict | duplicate | skip | delete
    reason: str = ""
    rom_name: str = ""
    kind: str = "move"      # "rename" (same directory) | "move" (different directory) | "m3u"
