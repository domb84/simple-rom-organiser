def bios_op(src: Path, known: Optional[Mapping[Path, Any]] = None) -> Optional[RenameOp]:
    """The op of a file no game matches when it is a BIOS / firmware file (told by its checksum: it stays where it is, under the name
    the emulators expect when the list says one) or an emulator's key file (told by its name: left as it is); None for any other file.
    ``known`` is what the scan found (``bios.find_in_scan``); without it the file is looked at."""
    from . import bios
    if bios.is_key_file(src):
        return RenameOp(src, src, "skip", "key file of an emulator - left in place", "", "move", "", False, bios=True)
    if known is not None:
        hit = known.get(src)
        found, in_zip = (hit.bios, hit.in_zip) if hit is not None else (None, False)
    else:
        found = bios.identify_archive(src)
        in_zip = found is not None
        found = found or bios.identify(src)
    if found is None:
        return None
    if in_zip:                                                   # a zip of nothing but BIOS files: kept as it is
        return RenameOp(src, src, "ok", f"BIOS / firmware ({found.system}) in a zip, told by its checksum - kept with the ROMs",
                        found.name, "rename", "", False, bios=True, bios_game=found.game)
    why = f"BIOS / firmware ({found.system}), told by its checksum - kept with the ROMs"
    # the name it gets, as a ROM gets its DAT's: what the emulators look for (libretro's list) or else the list's own name for it (TOSEC's)
    target = found.name if found.source == "libretro" else safe_filename(found.name)
    if src.name.casefold() in (found.names if found.source == "libretro" else {target.casefold()}):
        return RenameOp(src, src, "ok", why, target, "rename", "", False, bios=True, bios_game=found.game)
    dst = src.with_name(target)
    if os.path.lexists(dst):
        return RenameOp(src, src, "skip", f"{why}; {target} is already here, so this copy keeps its name", target, "rename", "", False,
                        bios=True, bios_game=found.game)
    return RenameOp(src, dst, "move", why, target, "rename", "", False, bios=True, bios_game=found.game)


def bios_exclusion(op: RenameOp, profile: Optional["library.LibraryProfile"]) -> Optional[tuple[str, str, tuple[str, ...]]]:
    """A BIOS file named by a TOSEC firmware list is judged like a ROM of that list: its entry's name goes through the same parsing and
    the same rules (bad dump, over / under dump, modified ... and the dump types that are switched off). ``(why, exact flags, codes)``
    when one applies (the file is then set aside as a ROM would be), else None. The language, region and version rules pick between
    games: they do not apply."""
    if profile is None or not op.bios or not op.bios_game:
        return None
    from . import library
    why = library.eligibility(op.bios_game, library.STYLE_TOSEC, profile, languages=False)
    if not why:
        return None
    return (", ".join(library.tags.RULE_LABELS.get(c, c) for c, _t in why) + f": {op.bios_game}",
            " ".join(t for _c, t in why if t), tuple(c for c, _t in why))


def bios_out_of(kept: RenameOp, root: Path) -> Optional[RenameOp]:
    """A BIOS file lying in a reserved folder (``_unmatched`` ... a build set it aside): the op that brings it back to where it belongs,
    as a ROM that qualifies again comes back. None when its name is taken (it stays)."""
    if kept.status == "skip" and not kept.reason.startswith("key file"):
        return None
    core = folders.core_parts(_parts_of(kept.src, root))
    return dataclasses.replace(kept, dst=root.joinpath(*core[:-1], kept.dst.name), status="move", kind="move",
                               reason=kept.reason + "; back out of its reserved folder")


def bios_duplicates(ops: Sequence[RenameOp], root: Path, taken: Container[int] = ()) -> list[tuple[RenameOp, "library.Decision"]]:
    """The same BIOS twice (any folder) is a ROM twice: one copy stays, the spares go to ``_duplicates`` as the spare copies of a ROM
    do, and the copy that stays is chosen as for a ROM (``scanner.group_duplicate_units``): the one already in place and named right, then
    one outside the reserved folders, loose before a zip, then the fewest folders, the shortest path. A symbolic link is never touched,
    and a zip of several BIOS files is no copy of any one of them. The verdicts, not yet applied (``taken``: ops already decided)."""
    from . import scanner

    def rank(o: RenameOp) -> tuple:
        parts = _parts_of(o.src, root)
        return (o.status != "ok", scanner.is_set_aside_duplicate(o.src, root), folders.reserved_of(parts) is not None,
                o.src.suffix.lower() == ".zip", len(parts), len(str(o.src)), str(o.src).casefold())

    by_name: dict[tuple[str, str], list[RenameOp]] = {}
    for op in ops:
        if id(op) not in taken and op.bios and op.rom_name and op.status in ("ok", "move", "skip") and not os.path.islink(op.src) and _one_bios(op.src):
            by_name.setdefault((op.rom_name.casefold(), op.bios_game), []).append(op)
    out: list[tuple[RenameOp, "library.Decision"]] = []
    for group in by_name.values():
        if len(group) < 2:
            continue
        keeper = min(group, key=rank)
        rel = _rel_to(keeper.dst, root)
        text = rel.as_posix() if rel is not None else str(keeper.dst)
        for op in group:
            if op is not keeper:
                out.append((op, _verdict("duplicate", f"duplicate of {text}", keeper=text)))
    return out


def bios_flawed_beside_clean(ops: Sequence[RenameOp], root: Path, taken: Container[int] = ()) -> list[tuple[RenameOp, "library.Decision"]]:
    """A bad dump or modified BIOS (allowed: ``library.FLAWED_RULES`` not excluded) is kept only when no clean dump of the same entry is,
    as for a ROM (``library._flawed_beside_clean``): one beside a kept clean dump of that version is superseded by it."""
    from . import library

    groups: dict[tuple, list[tuple[RenameOp, bool]]] = {}
    for op in ops:
        if id(op) not in taken and op.bios and op.bios_game and op.status in ("ok", "move", "skip") and not os.path.islink(op.src) and _one_bios(op.src):
            t = library.tags.parse_name(op.bios_game, library.STYLE_TOSEC)
            key = (op.dat, t.title.casefold(), t.regions, t.languages, t.status, tuple(t.flags), t.version, t.date)
            groups.setdefault(key, []).append((op, bool(library.tags.exclusion_rules(t) & library.FLAWED_RULES)))
    out: list[tuple[RenameOp, "library.Decision"]] = []
    for group in groups.values():
        clean = [op for op, flawed in group if not flawed]
        if not clean:
            continue
        keeper = min(clean, key=lambda o: str(o.dst).casefold())
        rel = _rel_to(keeper.dst, root)
        text = rel.as_posix() if rel is not None else str(keeper.dst)
        for op, flawed in group:
            if flawed:
                out.append((op, _verdict("superseded", f"superseded by {text} (a clean dump of the same version)", superseded_by=text)))
    return out


def _one_bios(path: Path) -> bool:
    """True unless ``path`` is a zip of more than one file (a BIOS zip holds BIOS files only: ``bios.identify_archive``)."""
    if path.suffix.lower() != ".zip":
        return True
    try:
        with zipfile.ZipFile(path) as zf:
            return sum(1 for i in zf.infolist() if not i.is_dir()) <= 1
    except (OSError, zipfile.BadZipFile, ValueError, NotImplementedError):
        return True


def bios_verdicts(ops: Sequence[RenameOp], root: Path, profile: Optional["library.LibraryProfile"]) -> list[tuple[RenameOp, "library.Decision"]]:
    """What the checks on BIOS files decide, in their order: the rules set a flagged one aside (:func:`bios_exclusion`: never a symbolic
    link, never a zip of several BIOS files, which is judged by none of them), then a spare copy of one goes (:func:`bios_duplicates`), then a
    flawed one beside a clean dump of its version (:func:`bios_flawed_beside_clean`). Each file gets one verdict (the first)."""
    out: list[tuple[RenameOp, "library.Decision"]] = []
    taken: set[int] = set()
    for op in ops:
        if os.path.islink(op.src) or not _one_bios(op.src):
            continue
        hit = bios_exclusion(op, profile)
        if hit is not None:
            out.append((op, _verdict("excluded", hit[0], flags=hit[1], codes=hit[2])))
            taken.add(id(op))
    for check in (bios_duplicates, bios_flawed_beside_clean):
        more = check(ops, root, taken)
        taken.update(id(op) for op, _d in more)
        out.extend(more)
    return out


def _clone_op(op: RenameOp) -> RenameOp:
    """A shallow copy of ``op`` (``copy.copy`` without its generic machinery: one per file of a big scan)."""
    new = object.__new__(RenameOp)
    new.__dict__.update(op.__dict__)
    return new


def _fold_text(text: str) -> str:
    return os.path.normcase(text).casefold()


def _finish_op(src: Path, dst: Path, reasons: list[str], rom_name: str, dat: str,
               unmatched: bool) -> RenameOp:
    # (text work only: this runs for every file of a big scan, and a Path's ``parent`` / ``name`` were the hot spot.
    # str(): on Windows Path equality ignores case, which would hide a case-only rename)
    s, d = os.fspath(src), os.fspath(dst)
    same_parent = _fold_text(os.path.dirname(s)) == _fold_text(os.path.dirname(d))
    at_target = s == d or (os.path.basename(s) == os.path.basename(d) and same_parent and _same_file(src, dst))   # (a hard link elsewhere is not it)
    status = "ok" if at_target else "move"
    kind = "rename" if same_parent else "move"
    if at_target:
        dst = src
    return RenameOp(src, dst, status, ", ".join(reasons), rom_name, kind, dat, unmatched)


def _converted_op(src: Path, root: Path) -> RenameOp:
    """An original kept by Convert stays where it is; one in the legacy place moves to ``_converted_originals/``."""
    if _legacy_folder(src, root) is not None:
        dst = root.joinpath(CONVERTED_DIR, *folders.core_parts(_parts_of(src, root)))
        return RenameOp(src, dst, "move", "original kept by Convert", "", "move", "", True)
    return RenameOp(src, src, "ok", "original kept by Convert", "", "move", "", True)


class _Planner:
    """Per-plan settings for files that matched nothing."""

    def __init__(self, root: Path, missing_dats: Iterable[str],
                 layout: str = LAYOUT_PER_DAT, keep_bios: bool = True, bios_found: Optional[Mapping[Path, Any]] = None,
                 pinner: Any = None) -> None:
        self.root = root
        self.pinner = pinner                        # savepin.Pinner: a save in the folder is set aside under the game it belongs to
        self.layout = layout
        self.keep_bios = keep_bios                  # the library rule: BIOS / firmware / key files stay with the ROMs
        from . import bios
        bios.refresh()                              # (the TOSEC lists may have changed since the last plan)
        self.bios_found = bios_found                # what the scan found (None: look at each file)
        # The "folder of a DAT that is not loaded" rule only makes sense with DAT folders.
        self.missing_folders = ({dat_folder_name(n).casefold(): n for n in missing_dats if n}
                                if layout != LAYOUT_FLAT else {})

    def unmatched(self, src: Path, why: str) -> RenameOp:
        root = self.root
        if _is_converted_original(src, root):
            return _converted_op(src, root)
        info = folders.classify(_parts_of(src, root))
        if info is not None:
            name, legacy = info
            if legacy:   # a file in a reason folder of the old layout: the folder moves to the top level
                code = next((c for c, d in CODE_DIRS.items() if d == name), "")
                op = RenameOp(src, root.joinpath(name, *folders.core_parts(_parts_of(src, root))), "move", why,
                              "", "move", "", True)
                op.code = code
                return op
            kept = bios_op(src, self.bios_found) if self.keep_bios else None
            back = bios_out_of(kept, root) if kept is not None else None         # (a BIOS an earlier build set aside comes back, as a ROM does)
            if back is not None:
                return back
            if name == UNMATCHED_DIR:                  # a save an earlier build put in _unmatched, that can be pinned to a game now
                pinned = self._pin(src)
                if pinned is not None:
                    return pinned
            return RenameOp(src, src, "ok", f"{why}, already in {name}", "", "move", "", True)
        rel = _rel_to(src, root)
        if rel is None:
            return RenameOp(src, src, "skip", "outside the selected folder", "", "move", "", True)
        if len(rel.parts) > 1 and rel.parts[0].casefold() in self.missing_folders:
            dat = self.missing_folders[rel.parts[0].casefold()]
            return RenameOp(src, src, "skip", f"{why}, but the DAT '{dat}' is not loaded - left in its folder",
                            "", "move", "", True)
        if self.layout == LAYOUT_FLAT and len(rel.parts) > 1 and rel.parts[0].casefold() in KEEP_DIRS:
            return RenameOp(src, src, "skip", "frontend media folder - left in place", "", "move", "", True)
        if _is_keep_file(src) and not any(x.endswith(" (WHDLoad install)") for x in src.parts):      # (no frontend file lies in an old install)
            return RenameOp(src, src, "skip", "frontend / emulator file - left in place", "", "move", "", True)
        kept = bios_op(src, self.bios_found) if self.keep_bios else None
        if kept is not None:
            return kept
        pinned = self._pin(src)
        if pinned is not None:
            return pinned
        return _finish_op(src, root / UNMATCHED_DIR / rel, [why], "", "", True)

    def _pin(self, src: Path) -> Optional[RenameOp]:
        """The op that sets a save aside under the game it belongs to (``_saves/<Title>/``), or None when it is not pinned to one."""
        if self.pinner is None:
            return None
        titles = self.pinner.titles(src)
        if not titles:
            return None
        from . import savepin
        op = _finish_op(src, savepin.destination(self.root, titles[0], src.name),
                        [f"a save of {titles[0]}" + (f" (and {len(titles) - 1} more)" if len(titles) > 1 else "")], "", "", True)
        op.copies = tuple(titles[1:])
        op.folder = folders.SAVES_DIR
        return op


def _matched_op(src: Path, root: Path, roms: Sequence["Rom"], archive_ext: Optional[str],
                layout: str = LAYOUT_PER_DAT, matched_via: str = "raw",
                byte_order: str = "") -> tuple[RenameOp, "Rom"]:
    """Op for a loose file (``archive_ext`` None) or a single-game archive, and its rom."""
    if archive_ext is None:
        rom, alts = choose_rom(src.name, roms,
                               key=lambda r: _target_name(r, src.name, None, matched_via, byte_order))
    else:
        stem, _ = _split_ext(src.name)
        rom, alts = choose_rom(stem, roms, key=_archive_stem)
        alts = [r for r in alts if _archive_stem(r) != _archive_stem(rom)]
    target = _target_name(rom, src.name, archive_ext, matched_via, byte_order)
    reasons: list[str] = []
    safe = safe_filename(target)
    if safe != target:
        reasons.append("sanitised for filesystem")
    if matched_via == "headerless":
        reasons.append("matched with its header skipped (file kept as is)")
    elif matched_via == "container":
        reasons.append("matched through its compressed disc image (file kept as is)")
    elif matched_via == "byteswapped":
        reasons.append(f"matched byte-swapped{f' ({byte_order})' if byte_order else ''} (file kept as is)")
    if alts:
        reasons.append("alternatives: " + "; ".join(r.name for r in alts[:5])
                       + (" ..." if len(alts) > 5 else ""))
    dst = canonical_dir(root, rom.dat, layout) / safe
    return _finish_op(src, dst, reasons, rom.name, rom.dat, False), rom


HEADERLESS_EXTS = {".unh"}  # DAT roms without the header emulators need (NES)


def _header_form(rom: "Rom", matched_via: str) -> str:
    """``"headerless"`` for a file that *is* a headerless dump (raw match of a ``.unh`` rom),
    else ``""``. Latest-only compares versions only within one form, so a newer headerless
    ``.unh`` never sends away the only playable (iNES-headered) copy of a game."""
    if matched_via == "raw" and _split_ext(rom.name)[1].lower() in HEADERLESS_EXTS:
        return "headerless"
    return ""


def reason_destination(src: Path, root: Path, reason_dir: str) -> Path:
    """``root/<reason_dir>/<rel_core>``: ``rel_core`` is the path relative to ``root`` with a leading
    reserved folder (``_unmatched/``, ``_excluded/`` ... or the legacy ``_unmatched/_excluded/``)
    removed. The file name is unchanged, so a file already in another reason folder keeps its place
    in the tree."""
    rel = _rel_to(src, root)
    if rel is None:
        raise ValueError(f"path outside the folder: {src}")
    return root.joinpath(reason_dir, *folders.core_parts(rel.parts))


@dataclass
class MatchedUnit:
    """One matched file the organiser treats as one game: a loose file, or an archive whose members
    all match one game of one DAT (see :func:`matched_units`)."""

    path: Path                 # absolute
    op: RenameOp               # its canonical op (move / ok / conflict later)
    rom: "Rom"                 # the rom chosen by :func:`choose_rom`
    key: frozenset             # {unit_key(rom)} of the primary roms the file stands for
    form: str                  # :func:`_header_form`
    dat: str
    raw: bool                  # exact DAT content (not an alternate-hash match)
    archive: bool
    link: bool                 # symbolic link: never touched
    member: Optional[str] = None
    members: int = 1
    style: str = "tosec"


def _collect(result: "ScanResult", root: Path) -> tuple[dict[Path, "Match"], set[Path],
                                                       dict[Path, list[tuple["Entry", Optional["Match"]]]]]:
    loose_matched: dict[Path, "Match"] = {}
    loose_unmatched: set[Path] = set()
    archives: dict[Path, list[tuple["Entry", Optional["Match"]]]] = {}
    for m in result.matched:
        p = _abs(m.entry.path, root)
        if m.entry.member is None:
            loose_matched.setdefault(p, m)
        else:
            archives.setdefault(p, []).append((m.entry, m))
    for e in result.unmatched:
        p = _abs(e.path, root)
        if e.member is None:
            loose_unmatched.add(p)
        else:
            archives.setdefault(p, []).append((e, None))
    return loose_matched, loose_unmatched, archives


def _scan_units(result: "ScanResult", layout: Optional[str] = None,
                planner: Optional[_Planner] = None) -> tuple[list[MatchedUnit], list[RenameOp]]:
    """``(units, other ops)``; ``other ops`` (unmatched / skipped / converted originals / unsupported /
    unreadable files) are only built when a ``planner`` is given.

    The planner-independent part (the units) is worked out once per scan result and layout and handed out as copies:
    the plan edits its ops, and every preview / total used to rebuild all of them."""
    root = result.root
    if layout is None:
        layout = getattr(result, "layout", LAYOUT_PER_DAT) or LAYOUT_PER_DAT
    units, others, unmatched_loose, unmatched_archives = _base_units(result, layout)
    units = [dataclasses.replace(u, op=_clone_op(u.op)) for u in units]
    others = [_clone_op(o) for o in others]
    if planner is not None:
        for p in unmatched_loose:
            others.append(planner.unmatched(p, "no DAT match"))
        for p, why in unmatched_archives:
            others.append(planner.unmatched(p, why))
        for p in result.unsupported:
            ap = _abs(Path(p), root)
            if str(p).lower().endswith(".rvz"):
                others.append(planner.unmatched(ap, "unsupported disc image"))
            else:                                    # (an archive no 7z here can open: what is in it is not known - left where it is,
                op = RenameOp(ap, ap, "skip", "could not be read: 7z is not installed")   #  never moved; no game you have)
                op.code = "unmatched"
                others.append(op)
        for p, msg in result.errors:
            ap = _abs(Path(p), root)
            if re.search(r"\b(BadZipFile|EOFError)\b", msg) and os.path.isfile(ap) and not os.path.islink(ap):
                others.append(planner.unmatched(ap, f"could not be read (a damaged archive): {msg}"))      # (it matches nothing: not a game)
            else:                                    # (a read error that may pass: the file is left where it is)
                others.append(RenameOp(ap, ap, "skip", f"could not be read: {msg}"))
    return units, others


def _base_units(result: "ScanResult", layout: str) -> tuple[list[MatchedUnit], list[RenameOp], list[Path], list[tuple[Path, str]]]:
    if not getattr(result, "cache_units", False):    # only the server, which never edits a finished scan, opts in
        return _build_units(result, layout)
    cache = result.__dict__.setdefault("_base_units_cache", {})
    if layout not in cache:
        cache[layout] = _build_units(result, layout)
    return cache[layout]


def _build_units(result: "ScanResult", layout: str) -> tuple[list[MatchedUnit], list[RenameOp], list[Path], list[tuple[Path, str]]]:
    from .datfile import unit_key

    root = result.root
    loose_matched, loose_unmatched, archives = _collect(result, root)
    units: list[MatchedUnit] = []
    others: list[RenameOp] = []
    unmatched_archives: list[tuple[Path, str]] = []

    def style_of(rom: "Rom") -> str:
        from .tags import style_of_rom
        return style_of_rom(rom)

    for p, m in loose_matched.items():
        if _is_converted_original(p, root):
            others.append(_converted_op(p, root))
            continue
        via = getattr(m, "matched_via", "raw") or "raw"
        op, rom = _matched_op(p, root, m.primary, None, layout, via, getattr(m, "byte_order", "") or "")
        if getattr(m, "container", "") == "id":            # (told by the game / title ID in the file: no checksum exists for it)
            op.reason = op.reason.replace("matched through its compressed disc image", "identified by the ID in the file, not by a checksum")
        units.append(MatchedUnit(p, op, rom, frozenset(unit_key(r) for r in m.primary), _header_form(rom, via),
                                 rom.dat, via == "raw", False, os.path.islink(p), None, 1, style_of(rom)))
    unmatched_loose = sorted(loose_unmatched - set(loose_matched), key=os.fspath)

    for p, members in archives.items():
        if _is_converted_original(p, root):
            others.append(_converted_op(p, root))
            continue
        matches = [m for _, m in members if m is not None]
        n = len(members)
        _, ext = _split_ext(p.name)
        if not matches:
            unmatched_archives.append((p, "no DAT match" if n == 1 else f"none of {n} members match"))
            continue
        if len(matches) == n:
            # All members matched: usable if they belong to one game (set) of one DAT.
            dat = matches[0].dat
            games: Optional[set[str]] = None
            for m in matches:
                g = {_archive_stem(r) for r in m.primary} if m.dat == dat else set()
                games = g if games is None else games & g
            if games:
                roms = [r for r in matches[0].primary if _archive_stem(r) in games]
                op, rom = _matched_op(p, root, roms, ext, layout)
                if n > 1:
                    _add_reason(op, f"archive holds {n} roms of one game")
                via = getattr(matches[0], "matched_via", "raw") or "raw"
                key = frozenset(unit_key(r) for m in matches for r in m.primary if _archive_stem(r) in games)
                units.append(MatchedUnit(p, op, rom, key, _header_form(rom, via), rom.dat, via == "raw",
                                         True, os.path.islink(p), members[0][0].member, n, style_of(rom)))
                continue
        others.append(RenameOp(p, p, "skip", f"archive has {n} members ({len(matches)} matched)"))
    return units, others, unmatched_loose, unmatched_archives


def partial_archives(result: "ScanResult") -> list[MatchedUnit]:
    """The archives that hold one game's ROM(s) next to other files (a readme, a picture): the build leaves them as they are (it cannot
    rename the archive of only part of it), but the game is one you have. One unit each, for the counts (the totals)."""
    root = result.root
    _lm, _lu, archives = _collect(result, root)
    out: list[MatchedUnit] = []
    for p, members in archives.items():
        matches = [m for _, m in members if m is not None]
        if not matches or len(matches) == len(members) or _is_converted_original(p, root):
            continue
        dat = matches[0].dat
        games: Optional[set[str]] = None
        for m in matches:
            g = {_archive_stem(r) for r in m.primary} if m.dat == dat else set()
            games = g if games is None else games & g
        if not games:
            continue
        roms = [r for r in matches[0].primary if _archive_stem(r) in games]
        via = getattr(matches[0], "matched_via", "raw") or "raw"
        from .tags import style_of_rom
        op = RenameOp(p, p, "skip", "", roms[0].name)
        member = next(e.member for e, m in members if m is not None)          # (the game's file in it: a playlist names that one)
        out.append(MatchedUnit(p, op, roms[0], frozenset(), _header_form(roms[0], via), roms[0].dat, via == "raw", True,
                               os.path.islink(p), member, len(members), style_of_rom(roms[0])))
    return out


def matched_units(result: "ScanResult", layout: Optional[str] = None) -> list[MatchedUnit]:
    """The matched files the organiser treats as one game each (originals kept by Convert excluded).
    :func:`scanner.duplicate_groups` groups these."""
    return _scan_units(result, layout)[0]


def _platform_for(result: "ScanResult", platform: Any = None) -> Any:
    """The platform whose DATs the scan used (``platform`` if given), else a generic stand-in
    where "latest versions" applies to every DAT."""
    if platform is not None:
        return platform
    names = set(getattr(result, "dat_names", ()) or ())
    try:
        from .platforms import list_platforms

        for p in list_platforms():
            if names and names <= set(p.dats):
                return p
    except Exception:  # platforms unavailable: use the stand-in
        pass
    from types import SimpleNamespace

    dats = tuple(getattr(result, "dat_names", ()) or ())
    return SimpleNamespace(name="", dats=dats, latest_dats=dats, best_variant_dats=(), m3u_dats=())


def _verdict(code: str, why: str, *, missing: tuple[int, ...] = (), flags: str = "", superseded_by: str = "",
             codes: tuple[str, ...] = (), keeper: str = "") -> "library.Decision":
    """A decision to set a file aside (``code``: ``excluded`` | ``superseded`` | ``incomplete`` | ``duplicate``) for ``why``: what the rules
    decide for a file (``library.select``) and what the checks that need no rules decide (a spare copy, a BIOS) are the same thing."""
    from . import library
    return library.Decision(-1, code, codes=tuple(codes), detail=flags, superseded_by=superseded_by, missing=tuple(missing), reason=why, keeper=keeper)


def _set_aside(op: RenameOp, root: Path, d: "library.Decision") -> None:
    """THE one place a verdict that is not KEEP becomes an op: a move to ``<reason dir>/<rel path>`` (``ok`` if it is already there)."""
    reason_dir = CODE_DIRS[d.action]
    dst = reason_destination(op.src, root, reason_dir)
    new = _finish_op(op.src, dst, [], op.rom_name, op.dat, True)
    op.dst, op.status, op.kind, op.unmatched = new.dst, new.status, new.kind, True
    op.reason = (d.reason or d.action) + (f", already in {reason_dir}" if new.status == "ok" else "")
    op.code, op.keeper, op.missing, op.flags_text, op.superseded_by = d.action, d.keeper, tuple(d.missing), d.detail, d.superseded_by
    op.reasons = tuple(d.codes)
    op.bios = False                                         # (a BIOS file set aside is no BIOS the build keeps)


class _Core:
    """Result of one planning run (shared by :func:`plan_renames` and :func:`plan_library`)."""

    def __init__(self, ops: list[RenameOp], selection: Optional["library.Selection"],
                 owners: dict[int, tuple[RenameOp, MatchedUnit]]) -> None:
        self.ops, self.selection, self.owners = ops, selection, owners


def _plan_core(result: "ScanResult", missing_dats: Iterable[str], latest_only: bool,
               layout: Optional[str], profile: Optional["library.LibraryProfile"], platform: Any,
               ratings: Any = None, lang_games: Any = None, saved: Any = None) -> _Core:
    from . import scanner

    root = result.root
    if layout is None:
        layout = getattr(result, "layout", LAYOUT_PER_DAT) or LAYOUT_PER_DAT
    from . import savepin
    planner = _Planner(root, missing_dats, layout, keep_bios=profile.keep_bios if profile is not None else True,
                       bios_found=getattr(result, "bios_files", None), pinner=savepin.Pinner(getattr(result, "dats", None)))
    units, others = _scan_units(result, layout, planner)
    ops: list[RenameOp] = [u.op for u in units] + others
    links = {id(u.op) for u in units if u.link}        # the units already know (one lstat per file, done once)
    known = {id(u.op) for u in units}
    for op in ops:
        if op.status in MOVE_STATUSES and (id(op) in links if id(op) in known else os.path.islink(op.src)):
            op.status, op.dst, op.reason = "skip", op.src, "symbolic link - left in place"

    # What each check decides, in the order they run, and then one pass that makes the verdicts true (:func:`_apply_decision`):
    # spare copies of a rom first (independent of the library rules: one keeper per rom), then the rules, then the BIOS checks.
    verdicts: list[tuple[RenameOp, "library.Decision", bool]] = []         # (op, verdict, an archive that holds a game and other files)
    by_path = {u.path: u for u in units}
    losers: set[Path] = set()
    for keeper, group in scanner.duplicate_groups(result, layout, units=units):
        keeper_rel = _rel_to(keeper, root)
        keeper_text = keeper_rel.as_posix() if keeper_rel is not None else str(keeper)
        for path in group:
            u = by_path.get(path)
            if u is None:
                continue
            losers.add(path)
            verdicts.append((u.op, _verdict("duplicate", f"duplicate of {keeper_text}", keeper=keeper_text), False))

    selection = None
    owners: dict[int, tuple[RenameOp, MatchedUnit]] = {}
    if profile is None and latest_only:
        from . import library

        profile = library.LibraryProfile.latest_only_profile()
    if profile is not None:
        from . import library

        items = []
        have_rom = {(u.dat, u.rom.name) for u in units if not u.link and u.path not in losers}
        for u in units:
            if u.path in losers:
                continue
            if u.link:
                if (u.dat, u.rom.name) in have_rom:
                    continue      # a real file already stands for this rom
                have_rom.add((u.dat, u.rom.name))
            key = len(items)
            owners[key] = (u.op, u)
            items.append(library.Item(key, u.dat, u.rom, u.style, u.path, u.member, u.form, u.link,
                                      holds=frozenset(n for _d, n in u.key) if u.archive else frozenset()))
        # an archive that holds a game next to other files (a readme, scans) is never moved or renamed, but its game is yours: the
        # rules decide it like any file (a disk of a set fills its slot, a language sets it aside, your own choice for it holds)
        partial: set[int] = set()
        if platform is not None:
            skips = {_fold(op.src): op for op in others if op.status == "skip" and not op.code}
            for u in partial_archives(result):
                op = skips.get(_fold(u.path))
                if op is None:
                    continue
                key = len(items)
                owners[key] = (op, dataclasses.replace(u, op=op))
                partial.add(key)
                items.append(library.Item(key, u.dat, u.rom, u.style, u.path, u.member, u.form, u.link,
                                      holds=frozenset(n for _d, n in u.key) if u.archive else frozenset()))
        selection = library.select(items, profile, _platform_for(result, platform), ratings=ratings, lang_games=lang_games,
                                   saved=saved)
        for key, (op, u) in owners.items():
            if not u.link:                                      # (a symbolic link fills its slots / ranks like any file but is never moved)
                verdicts.append((op, selection.decisions.get(key), key in partial))

    verdicts.extend((op, d, False) for op, d in bios_verdicts(ops, root, profile))
    for op, d, whole in verdicts:
        _apply_decision(op, d, root, partial=whole)
    ops.sort(key=lambda o: (o.unmatched, o.dat, str(o.src).casefold()))
    _resolve_conflicts(ops, root)
    for op in ops:   # legacy layout: say why the file leaves _unmatched/<reason>/ ; record the target folder
        if op.status in MOVE_STATUSES:
            legacy = _legacy_folder(op.src, root)
            if legacy is not None:
                _add_reason(op, f"moved out of {UNMATCHED_DIR}/{legacy}/ (new layout)")
        op.folder = folders.top_folder(_parts_of(op.dst, root)) or ""
    ops.extend(_plan_m3u_ops(ops, root))
    return _Core(ops, selection, owners)


def plan_renames(result: "ScanResult", missing_dats: Iterable[str] = (),
                 latest_only: bool = False,
                 layout: Optional[str] = None, profile: Optional["library.LibraryProfile"] = None,
                 platform: Any = None) -> list[RenameOp]:
    """Build one op for every file found by the scan (matched, unmatched, unsupported, errors).

    ``missing_dats``: DAT names of the platform that were not loaded; unmatched
    files inside their folders are left alone (``skip``) instead of being swept
    into ``_unmatched/`` (``per_dat`` layout only). Unmatched files are always moved. ``layout`` (``"per_dat"`` | ``"flat"``) defaults to ``result.layout``.
    Files under ``_converted_originals/`` are always left alone (``ok``; the legacy
    ``_unmatched/_converted_originals/`` moves there).
    Our own m3u playlists that reference moving files get a ``delete`` op.

    Spare copies of one rom (same content, loose or archived) go to ``_duplicates/``
    (always; see :func:`scanner.duplicate_groups` for the keeper). With a library ``profile``
    (``latest_only=True`` stands for ``LibraryProfile.latest_only_profile()``) files the profile
    excludes / supersedes / finds incomplete go to ``_excluded/`` / ``_superseded/`` /
    ``_incomplete/`` (``<path relative to root>``, file name unchanged); a file there that no
    longer qualifies moves back to its canonical place. ``platform`` (default: found from the
    scan's DAT names) tells the profile which DATs each rule covers.
    """
    return _plan_core(result, missing_dats, latest_only, layout, profile, platform).ops


def _final_path(op: RenameOp) -> Path:
    return op.dst if (op.status in MOVE_STATUSES or op.status == "ok") else op.src


@dataclass
class LibraryPlan:
    """One preview for "Build library": file moves, playlist writes and removals, and why."""

    ops: list[RenameOp]                  # file moves + ``delete`` ops for stale own playlists
    playlists: list["m3u.M3UOp"]         # write | ok | conflict
    selection: "library.Selection"
    profile: "library.LibraryProfile"
    owners: dict = field(default_factory=dict)  # Item.key -> (its op, its unit): where each kept file ends up (WHDLoad games)

    def counts(self) -> dict[str, int]:
        out = plan_counts(self.ops)
        for k, v in reason_counts(self).items():
            if k.startswith("playlists_"):
                out[k] = v
        return out

    def exclusion_counts(self) -> dict[str, dict[str, int]]:
        """Excluded files per reason code (``library.Selection.exclusion_counts``: ``exclusive`` / ``any``)."""
        return self.selection.exclusion_counts()

    def vanish_summary(self) -> dict:
        """Titles none of whose variants is kept: ``{"titles", "by_reason", "by_code"}``."""
        return self.selection.vanish_summary()

    @property
    def vanished(self) -> list["library.Vanished"]:
        return self.selection.vanished


def plan_library(result: "ScanResult", profile: "library.LibraryProfile", missing_dats: Iterable[str] = (),
                 layout: Optional[str] = None, savedisk: bool = False,
                 labels: bool = True, platform: Any = None, ratings: Any = None, lang_games: Any = None,
                 saved: Any = None) -> LibraryPlan:
    """See :func:`_plan_library`; playlists on disk are looked at once for the whole plan (``m3u.one_look``)."""
    from . import m3u

    # (a plan makes some hundred thousand small objects that all live until it is done: the collector would look through them again and
    # again for cycles that are not there - a good tenth of the time of a big one - so it waits)
    collecting = gc.isenabled()
    gc.disable()
    try:
        with m3u.one_look():
            return _plan_library(result, profile, missing_dats, layout, savedisk, labels, platform, ratings, lang_games, saved)
    finally:
        if collecting:
            gc.enable()


def _plan_library(result: "ScanResult", profile: "library.LibraryProfile", missing_dats: Iterable[str] = (),
                 layout: Optional[str] = None, savedisk: bool = False,
                 labels: bool = True, platform: Any = None, ratings: Any = None, lang_games: Any = None,
                 saved: Any = None) -> LibraryPlan:
    """The combined plan: tidy + duplicates + the profile's rules + playlists of the kept multi-disk sets.

    Playlists are planned from the disks' FINAL paths (next to disk 1). Our own playlists that go
    stale (disks move away or are gone, or a planned playlist replaces them) get ``delete`` ops; one
    that is deleted and rewritten under the same name becomes a single ``write``.
    """
    from . import library, m3u

    core = _plan_core(result, missing_dats, False, layout, profile, platform, ratings, lang_games, saved)
    root = result.root
    ops = core.ops
    sel = core.selection if core.selection is not None else library.Selection()

    if _game_folders(profile, platform):
        _into_game_folders(core.owners, sel, root, platform)
    _into_system_folder(core.owners, sel, root, platform)
    whd, whd_games = _whdload_games(sel, core.owners, profile, platform)
    games = _amiga_game_dats(profile, platform)
    combine = getattr(sel, "combine_alt", True)

    def whdload_game(keys: Iterable[int]) -> bool:
        """True when the game of these disks is played from its WHDLoad build."""
        keys = [k for k in keys if k in core.owners]
        return bool(whd_games) and bool(keys) and library.game_key(_item_of(keys[0], core.owners), combine) in whd_games
    specs: list["m3u.PlaylistSpec"] = []
    counts: dict[str, int] = {}
    in_sets: set[int] = set()

    def disk_of(key: int, slot: int, label: str) -> Optional["m3u.PlaylistDisk"]:
        owner = core.owners.get(key)
        if owner is None:
            return None
        op, unit = owner
        if op.code:                                           # (set aside after the selection - a flawed BIOS beside a clean one: no disk of a playlist)
            return None
        final = _final_path(op)
        if unit.archive and unit.members > 1:
            counts[str(final)] = unit.members
        return m3u.PlaylistDisk(slot, final, unit.member if unit.archive else None, label)

    for cs in sel.sets:
        in_sets.update(cs.slots.values())
        disks = [d for slot, key in sorted(cs.slots.items()) if (d := disk_of(key, slot, cs.labels.get(slot, ""))) is not None]
        if len(disks) == len(cs.slots) and disks:
            if cs.dat in SYSTEM_DATS:
                continue                                      # (a Workbench or Kickstart set: no playlist, those are for games)
            if any(_fold(d.path) in whd for d in disks) or (cs.dat in games and whdload_game(cs.slots.values())):
                continue                                      # (the game is played from its WHDLoad build: no playlist)
            specs.append(m3u.PlaylistSpec(cs.name, cs.dat, cs.total, disks,
                                          [b["text"] for _i, b in sorted(cs.borrowed.items())],
                                          savedisk=True if cs.dat in games else None))
    if games:
        specs += _single_game_specs(sel, core.owners, games, frozenset(getattr(platform, "image_set_dats", ()) or ()), in_sets, whd,
                                    disk_of, whdload_game)
    playlists = m3u.plan_playlists(specs, root, savedisk=savedisk, labels=labels, member_counts=counts)

    moving = [str(op.src) for op in ops if op.status in MOVE_STATUSES]
    written = {_fold(p.path): Path(p.path) for p in playlists if p.status in ("write", "ok")}

    def rewritten(old: Path) -> bool:
        """True when a planned playlist IS ``old`` (its name, or another case of it on a file system that ignores case): writing it
        replaces it. An old one whose name differs only in case on one that does not is another file, removed on its own."""
        new = written.get(_fold(old))
        return new is not None and (str(new) == str(old) or (os.path.exists(new) and _same_file(Path(old), new)))

    kept_ops: list[RenameOp] = []
    deleting: set[str] = set()
    by_src = {_fold(o.src): o for o in ops if o.kind != "m3u"}
    for op in ops:
        if op.status == DELETE_STATUS and op.kind == "m3u":
            if rewritten(op.src):
                continue
            deleting.add(_fold(op.src))
            op.reason = _library_delete_reason(op, by_src)
        kept_ops.append(op)
    for st in m3u.plan_stale(root, playlists, moving, whd):
        if _fold(st.path) in deleting or rewritten(st.path):
            continue
        deleting.add(_fold(st.path))
        kept_ops.append(RenameOp(st.path, st.path, DELETE_STATUS, st.reason, "", "m3u"))
    _archive_paths(core.owners, kept_ops, platform)
    return LibraryPlan(kept_ops, playlists, sel, profile, core.owners)


GAMES_DIR = "Commodore Amiga - Games"          # the Amiga's kept games: <root>/Commodore Amiga - Games/<title>/ (the disks or the original, the CD32 disc, the WHDLoad install)


SYSTEM_DIR = "Commodore Amiga - System"        # the Amiga's system disks: <root>/Commodore Amiga - System/<Workbench | Kickstart-Disks | Firmware>/
SYSTEM_DATS = {"Commodore Amiga - Operating Systems - Workbench": "Workbench", "Commodore Amiga - Kickstart-Disks": "Kickstart-Disks",
               "Commodore Amiga - Firmware": "Firmware"}
_DISK_OF_SET = re.compile(r"\(Disk \d+ of \d+\)(\([^)]*\))?")     # (the disk's place in its set and the label after it)


def _release_folder(name: str) -> str:
    """The release a Workbench disk is of: its DAT entry without the disk's place in the set and without the dump flags ("Workbench v1.1 rev
    31.334 (1986)(Commodore)" for each disk of each dump of it)."""
    stem = _DISK_OF_SET.sub("", Path(name).stem)
    return safe_filename(re.sub(r"\s+", " ", re.sub(r"\[[^\]]*\]", "", stem)).strip()) or safe_filename(Path(name).stem)


def _system_parts(dat: str, name: str) -> tuple[str, ...] | None:
    sub = SYSTEM_DATS.get(dat)
    return None if sub is None else (SYSTEM_DIR, sub) + ((_release_folder(name),) if sub == "Workbench" else ()) + (name,)


def layout_parts(platform: Any, dat: str, name: str, title: str = "") -> tuple[str, ...] | None:
    """THE place of a file in the Amiga's library layout, as parts below the system's folder (the archive lays what it sets aside out the
    same way, below the reason folder): a system disk under ``Commodore Amiga - System/<Workbench | Kickstart-Disks | Firmware>/`` (the
    Workbench disks in a folder of their release too), a game's file under ``Commodore Amiga - Games/<title>/``. None for every other file
    (the folder of its DAT, or flat)."""
    if dat in (getattr(platform, "dats", ()) or ()):
        system = _system_parts(dat, name)
        if system is not None:
            return system
    if title and dat in _amiga_game_dats_all(platform):
        return (GAMES_DIR, title, name)
    return None


def unit_dat(op: RenameOp, unit: Any) -> str:
    """The DAT of a file: its unit's (a zip that holds the game and other files has a row that names no DAT; its unit does)."""
    return op.dat or getattr(unit, "dat", "") or ""


def _into_system_folder(owners: dict, sel: Any, root: Path, platform: Any) -> None:
    """Send each kept file of the Amiga's system DATs - Workbench, the Kickstart disks, the firmware - to ``<root>/Commodore Amiga - System/``:
    each in a folder of its DAT's short name, the Workbench disks in a folder of their release too (no playlist: those are for games). The
    files keep the name of the DAT entry they match."""
    from . import library
    here = {d: sub for d, sub in SYSTEM_DATS.items() if d in (getattr(platform, "dats", ()) or ())}
    if not here:
        return
    for key, (op, unit) in owners.items():
        d = sel.decisions.get(key)
        sub = here.get(unit.dat)
        if (sub is None or op.code or op.unmatched or unit.link or op.status not in ("ok", "move")
                or (d is not None and d.action != library.KEEP)):
            continue
        new = _finish_op(op.src, Path(root).joinpath(*layout_parts(platform, unit.dat, op.dst.name)), [], op.rom_name, op.dat, False)
        op.dst, op.status, op.kind = new.dst, new.status, new.kind
        if op.status == "move":
            op.reason = ", ".join(x for x in (op.reason, "into the system folder") if x)


def _game_folders(profile: Any, platform: Any) -> bool:
    """The Amiga with "One version per game" and "Best variant": one folder per game under ``Commodore Amiga - Games`` (see :func:`_into_game_folders`)."""
    return (platform is not None and bool(getattr(platform, "image_set_dats", ()) or ()) and bool(getattr(profile, "one_per_game", False))
            and bool(getattr(profile, "best_variant", False)))


def _game_folder_names(games: dict[tuple, list[int]], owners: dict) -> dict[tuple, str]:
    """The folder name of each game (``library.game_key`` -> the keys of its files): its plain title; two games of one title get the publisher's
    name, then the year, added."""
    from . import library
    by_title: dict[str, list[tuple]] = {}
    tag: dict[tuple, Any] = {}
    for g, keys in games.items():
        tag[g] = library._tags_of(_item_of(min(keys), owners))
        by_title.setdefault(safe_filename(tag[g].title).casefold(), []).append(g)
    taken: set[str] = set()
    folder: dict[tuple, str] = {}
    for _title, group in sorted(by_title.items()):
        for g in sorted(group, key=lambda g: (tag[g].publisher.casefold(), tag[g].date, g)):
            t = tag[g]
            name = safe_filename(t.title)
            for extra in ((), (t.publisher,), (t.publisher, t.date[:4])):
                name = safe_filename(t.title + "".join(f" ({x})" for x in extra if x))
                if len(group) == 1 or name.casefold() not in taken:
                    break
            n = 1
            while name.casefold() in taken:                         # (the same everything: a number)
                n += 1
                name = safe_filename(f"{t.title} ({n})")
            taken.add(name.casefold())
            folder[g] = name
    return folder


def _archive_paths(owners: dict, ops: list[RenameOp], platform: Any) -> None:
    """The Amiga's files the rules set aside (``_excluded`` ...) lie in the archive as they would in the library (:func:`layout_parts`): each
    game in a folder of its own under ``Commodore Amiga - Games`` (:func:`_game_folder_names`, per reason folder), the system disks under
    ``Commodore Amiga - System`` (``op.archive_rel``, below the reason folder). Another system's files, and those no DAT knows, keep their
    path."""
    from . import library
    game_dats = _amiga_game_dats_all(platform)
    systems = [d for d in SYSTEM_DATS if d in (getattr(platform, "dats", ()) or ())]
    if not game_dats and not systems:
        return
    by_op = {id(op): key for key, (op, _u) in owners.items()}
    games: dict[str, dict[tuple, list[int]]] = {}                      # (per reason folder: a game's folder is named within it)
    for op in ops:
        key = by_op.get(id(op))
        if key is None or op.folder not in REASON_DIRS or op.status not in ("move", "ok", "rename"):
            continue
        dat = unit_dat(op, owners[key][1])
        if dat in systems:
            op.archive_rel = "/".join(layout_parts(platform, dat, op.dst.name))
        elif dat in game_dats:
            games.setdefault(op.folder, {}).setdefault(library.game_key(_item_of(key, owners), True), []).append(key)
    for group in games.values():
        folder = _game_folder_names(group, owners)
        for g, keys in group.items():
            for key in keys:
                op = owners[key][0]
                op.archive_rel = "/".join(layout_parts(platform, owners[key][1].dat, op.dst.name, folder[g]))


TIDY_EXTS = (".adf", ".ipf", ".zip", ".7z", ".lha", ".lzx", ".dms", ".adz", ".cue", ".iso", ".bin", ".chd", ".wav", ".m3u")     # (a game's files)


def tidy_archive_parts(platform: Any, parts: Any) -> tuple[str, ...] | None:
    """Where a file lies in the archive as the layout has it NOW, or None when it lies so already. ``parts`` is its path below the system's
    part of the archive. The reason folders have no leading underscore (``_excluded/x`` -> ``Excluded/x``, any system); the Amiga's files
    that earlier builds archived the old way (``_excluded/Commodore Amiga - Games - [ADF]/<file>``) go in a folder per game below
    ``Commodore Amiga - Games`` (the system disks under ``Commodore Amiga - System``), as :func:`layout_parts` has it. ``Unmatched`` keeps the
    source path, an install of WHDLoad stays as it is."""
    parts = tuple(parts)
    if len(parts) < 2:
        return None
    reason = folders.from_archive(parts[0])
    if reason is None or reason == folders.SAVES_DIR or reason not in folders.ARCHIVE_NAMES:
        return None
    top = folders.archive_dir(reason)
    rest = parts[1:]
    new = None
    if (reason in REASON_DIRS and len(parts) >= 3 and rest[0] not in (GAMES_DIR, SYSTEM_DIR)
            and getattr(platform, "image_set_dats", None) and not any(p.endswith("(WHDLoad install)") for p in parts[:-1])):
        name = parts[-1]
        if rest[0] in SYSTEM_DATS:
            new = _system_parts(rest[0], name)
        elif name.lower().endswith(TIDY_EXTS):
            from . import tags
            stem = name.rsplit(".", 1)[0]
            title = safe_filename(tags.parse_name(stem, "tosec").title)
            new = (GAMES_DIR, title or stem, name) if title else None
    out = (top,) + (new if new is not None else rest)
    return out if out != parts else None


def _amiga_game_dats_all(platform: Any) -> frozenset:
    """The DATs of the Amiga's games: its Games DAT, the SPS releases and the discs (the library's games folder)."""
    if platform is None or not getattr(platform, "image_set_dats", None):
        return frozenset()
    return frozenset(d for d in ((getattr(platform, "game_dat", "") or ""), *platform.image_set_dats, *(getattr(platform, "disc_dats", ()) or ())) if d)


def _into_game_folders(owners: dict, sel: Any, root: Path, platform: Any) -> None:
    """Send each kept file of a game - its SPS zip, its floppy set, its CD32 disc - to ``<root>/Commodore Amiga - Games/<title>/`` instead of the folder of
    its DAT (the playlist of a set and the WHDLoad install, written beside the disks, follow them). The title is the game's, without year or
    publisher; two games of one title (``library.KEEP_APART``) get the publisher's name, then the year, added."""
    from . import library
    wanted = {getattr(platform, "game_dat", "")} | set(platform.image_set_dats) | set(getattr(platform, "disc_dats", ()) or ())
    combine = getattr(sel, "combine_alt", True)
    games: dict[tuple, list[int]] = {}
    for key, (op, unit) in owners.items():
        d = sel.decisions.get(key)
        whole = op.status == "skip" and unit.archive and Path(op.src) == Path(op.dst)       # (an archive that holds the game and other files: moved as it is)
        if d is None or d.action != library.KEEP or unit.link or (op.status not in ("ok", "move") and not whole) or op.unmatched:
            continue
        item = _item_of(key, owners)
        if item.dat in wanted:
            games.setdefault(library.game_key(item, combine), []).append(key)
    folder = _game_folder_names(games, owners)
    for g, keys in games.items():
        for key in keys:
            op = owners[key][0]
            new = _finish_op(op.src, Path(root).joinpath(*layout_parts(platform, owners[key][1].dat, op.dst.name, folder[g])), [], op.rom_name, op.dat, False)
            op.dst, op.status, op.kind = new.dst, new.status, new.kind
            if op.status == "move":
                op.reason = ", ".join(x for x in (op.reason, "into the game's folder") if x)


def _amiga_game_dats(profile: Any, platform: Any) -> frozenset:
    """The DATs whose kept games get a playlist with a blank save disk when they have no WHDLoad build - one disk or several (the
    Amiga's games: its Games DAT and the SPS releases); empty on every other system."""
    from . import library
    if platform is None or "build_whdload" not in library.applicable_fields(platform):
        return frozenset()
    return frozenset(d for d in (getattr(platform, "game_dat", "") or "",) + tuple(getattr(platform, "image_set_dats", ()) or ()) if d)


def _item_of(key: int, owners: dict) -> Any:
    """The ``library.Item`` of a kept unit (what ``library.game_key`` takes)."""
    from . import library
    op, u = owners[key]
    return library.Item(key=key, dat=u.dat, rom=u.rom, style=u.style, path=_final_path(op), member=u.member)


def _whdload_games(sel: Any, owners: dict, profile: Any, platform: Any) -> tuple[set[str], set[tuple]]:
    """``(disks, games)`` of the WHDLoad games this build makes ("Build WHDLoad games" on): the folded paths of the disks each is built
    from (where they are and where the build puts them) and the games (``library.game_key``). A game played from its ``.lha`` gets no
    playlist, for none of its releases (an SPS original kept beside the floppies it is built from included)."""
    from types import SimpleNamespace

    from . import library, whdbuild, whdready
    if platform is None or not getattr(profile, "build_whdload", False) or "build_whdload" not in library.applicable_fields(platform):
        return set(), set()
    places: dict[str, tuple[str, str]] = {}
    by_place: dict[str, int] = {}
    for key, (op, _u) in owners.items():
        pair = (_fold(op.src), _fold(_final_path(op)))
        places[pair[0]] = places[pair[1]] = pair
        by_place.setdefault(pair[0], key)
        by_place.setdefault(pair[1], key)
    disks: set[str] = set()
    games: set[tuple] = set()
    combine = getattr(sel, "combine_alt", True)
    for t in whdbuild.targets(SimpleNamespace(selection=sel, owners=owners), platform):
        if not t.sps and (whdready.checked(t.names) or {}).get("ok") is False:
            continue                                          # (its install failed here: played from its disks, with a playlist)
        for path, _member in t.disks:
            disks.update(places.get(_fold(path), (_fold(path),)))
        key = by_place.get(_fold(t.disks[0][0])) if t.disks else None
        if key is not None:
            games.add(library.game_key(_item_of(key, owners), combine))
    return disks, games


def _single_game_specs(sel: Any, owners: dict, games: frozenset, image_sets: frozenset, in_sets: set[int], whd: set[str],
                       disk_of: Callable[[int, int, str], Any], whdload_game: Callable[[Iterable[int]], bool]) -> list[Any]:
    """Playlists of the kept Amiga games that are no multi-disk set and have no WHDLoad build: a game of one disk, and an SPS release
    (its images in name order), each with a blank save disk to save to."""
    from . import library, m3u
    groups: dict[tuple[str, str], list[int]] = {}             # (DAT, playlist name) -> its disks
    for key, d in sel.decisions.items():
        if d.action != library.KEEP or key in in_sets or key not in owners:
            continue
        op, u = owners[key]
        if u.dat not in games or getattr(op, "bios", False):
            continue
        if u.dat in image_sets:
            if u.rom.game:
                groups.setdefault((u.dat, u.rom.game), []).append(key)
            continue
        disk = library.tags._disk(library.tags.parse_name(u.rom.name, library.STYLE_TOSEC))
        if disk is None or disk[2] < 2:                       # (a disk of a multi-disk release with no set: left alone)
            groups.setdefault((u.dat, Path(u.rom.name).stem), []).append(key)
    out = []
    for (dat, name), keys in sorted(groups.items()):
        keys.sort(key=lambda k: (owners[k][1].rom.name.casefold(), k))
        units: dict[tuple, int] = {}
        for k in keys:                                        # (one line a disk: a file, or an image in the release's zip / 7z)
            units.setdefault((_fold(_final_path(owners[k][0])), owners[k][1].member if owners[k][1].archive else None), k)
        disks = [d for i, k in enumerate(units.values(), 1) if (d := disk_of(k, i, "")) is not None]
        if disks and not any(_fold(d.path) in whd for d in disks) and not whdload_game(keys):
            out.append(m3u.PlaylistSpec(name, dat, len(disks), disks, savedisk=True))
    return out


def _apply_decision(op: RenameOp, d: Any, root: Path, partial: bool = False) -> None:
    """What the rules decided (``library.select``) for a file, made true on its op: one they set aside goes to its reason folder (and from
    there to the archive) under its own name; one they keep gets the notes of why it is kept (a disk borrowed for a set, saves you have).
    ``partial``: an archive that holds a game next to other files (an SPS release with its scans and manual) is never renamed or repacked,
    only moved as it is: one they keep that lies in a reserved folder (``_unmatched``, from before its DAT knew it) goes back to where it
    came from, a kept one stays, or goes to its game's folder (:func:`_into_game_folders`)."""
    from . import library
    if d is None:
        return
    if d.action != library.KEEP:
        if d.action in CODE_DIRS:
            _set_aside(op, root, d)
        return
    if partial:
        parts = _parts_of(op.src, root)
        if folders.reserved_of(parts) is None:
            return
        dst = root.joinpath(*folders.core_parts(parts))
        if dst != op.src and not os.path.lexists(dst):
            op.dst, op.status, op.kind = dst, "move", "move"
            op.reason = (op.reason + "; " if op.reason else "") + "back out of its reserved folder (its game is kept)"
        return
    if library.BORROWED_CODE in d.codes:
        _add_reason(op, d.reason.split("; ")[-1])           # "borrowed as disk N of <set> (...)"
    if library.SAVED_KEEP in d.codes:
        _add_reason(op, d.reason)                           # "kept: you have saves or save states for it"


def _library_delete_reason(op: RenameOp, by_src: dict[str, RenameOp]) -> str:
    """Why Build library removes one of our playlists (its disks move away - nothing is "written again")."""
    from . import m3u

    info = m3u.read_m3u(op.src)
    moved = [by_src[_fold(e)] for e in (info[1] if info else []) if _fold(e) in by_src
             and by_src[_fold(e)].status in MOVE_STATUSES and by_src[_fold(e)].code]
    if not moved:
        return op.reason
    missing = sorted({m for o in moved if o.code == "incomplete" for m in o.missing})
    if missing:
        return (f"set incomplete (missing disk {', '.join(str(m) for m in missing)}) - playlist removed")
    codes = sorted({o.code for o in moved})
    return (f"{len(moved)} of its disks are set aside ({', '.join(codes)}) - playlist removed")


def _relocate_duplicate(holder: RenameOp, root: Path, claimed: dict[str, RenameOp]) -> bool:
    """Send a duplicate that blocks another file's target to ``_unmatched/``; True if possible."""
    rel = _rel_to(holder.src, root)
    if rel is None or _is_reserved_path(holder.src, root):
        return False
    new_dst = root / UNMATCHED_DIR / rel
    key = _fold(new_dst)
    if key in claimed or _exists(new_dst):
        return False
    holder.status, holder.dst, holder.unmatched, holder.kind = "move", new_dst, True, "move"
    _add_reason(holder, f"moved to {UNMATCHED_DIR}/ because it sits at another file's name")
    claimed[key] = holder
    return True


def _free_reason_targets(ops: list[RenameOp]) -> None:
    """Give every move into a ``_<reason>/`` folder a target nobody else holds.

    Reason destinations keep the file name, so two files with one relative path (or one that
    already sits at the target) would clash and the spare would stay where it is forever. They
    get ``name (2).ext``, ``name (3).ext`` ... instead. Nothing is ever merged or overwritten."""
    moving_away = {_fold(op.src) for op in ops if op.status in MOVE_STATUSES}
    taken = {_fold(op.dst) for op in ops if op.status not in MOVE_STATUSES}
    taken |= {_fold(op.dst) for op in ops if op.status in MOVE_STATUSES and not op.code}
    coded = [op for op in ops if op.status in MOVE_STATUSES and op.code]
    # a file that already carries the plain name has first claim on it
    for op in sorted(coded, key=lambda o: (str(o.src).casefold(), str(o.src))):
        key = _fold(op.dst)
        if key not in taken and (not _exists(op.dst) or key in moving_away or _same_file(op.src, op.dst)):
            taken.add(key)
            continue
        stem, ext = _split_ext(op.dst.name)
        n = 2
        while True:
            cand = op.dst.with_name(f"{stem} ({n}){ext}")
            ckey = _fold(cand)
            if ckey not in taken and ckey not in moving_away and not _exists(cand):
                break
            n += 1
        op.dst = cand
        taken.add(ckey)
        _add_reason(op, f"renamed to {cand.name}: the name is already taken there")


def _resolve_conflicts(ops: list[RenameOp], root: Optional[Path] = None) -> None:
    """Mark conflicts/duplicates between ops and against files already on disk."""
    _free_reason_targets(ops)
    # Files whose current path is going away.
    moving_away = {_fold(op.src) for op in ops if op.status in MOVE_STATUSES}
    by_src = {_fold(op.src): op for op in ops}
    # Targets held by files that stay where they are.
    staying = {_fold(op.dst): op for op in ops if op.status not in MOVE_STATUSES}
    claimed: dict[str, RenameOp] = {}
    relies: list[tuple[RenameOp, str]] = []  # ops that need another op to free their target

    # Files that already carry the target name get first claim on it.
    for op in sorted(ops, key=lambda o: (o.src.name != o.dst.name, str(o.src).casefold())):
        if op.status not in MOVE_STATUSES:
            continue
        key = _fold(op.dst)
        extra = ""
        holder = claimed.get(key) or staying.get(key)
        if holder is not None:
            if _same_content(op.src, holder.src):
                op.status, extra = "duplicate", f"same content as {holder.src.name}"
            else:
                op.status, extra = "conflict", f"target also wanted by {holder.src.name}"
        elif _exists(op.dst) and not _same_file(op.src, op.dst):
            if key in moving_away:
                extra = "target is moved away first"
                relies.append((op, key))
            elif op.dst.is_dir():
                op.status, extra = "conflict", "a directory exists at target"
            elif _same_content(op.src, op.dst):
                op.status, extra = "duplicate", "identical file already exists at target"
            else:
                op.status, extra = "conflict", "a different file exists at target"
        elif op.src.name != op.dst.name and op.src.name.casefold() == op.dst.name.casefold():
            extra = "case-only rename"
        if op.status in MOVE_STATUSES:
            claimed[key] = op
        if extra:
            _add_reason(op, extra)

    # Fixpoint: an op relying on its target being moved away fails if that file
    # ended up staying (duplicate / conflict). Duplicates are moved out of the way.
    changed = True
    while changed:
        changed = False
        for op, key in relies:
            if op.status not in MOVE_STATUSES:
                continue
            holder = by_src.get(key)
            if holder is None or holder.status in MOVE_STATUSES:
                continue
            changed = True
            if holder.status == "duplicate" and root is not None and _relocate_duplicate(holder, root, claimed):
                continue
            op.reason = ", ".join(r for r in op.reason.split(", ") if r != "target is moved away first")
            op.status = "conflict"
            _add_reason(op, f"target is occupied by {holder.src.name}, which stays ({holder.status})")
            if claimed.get(_fold(op.dst)) is op:
                del claimed[_fold(op.dst)]


def _plan_m3u_ops(ops: list[RenameOp], root: Path) -> list[RenameOp]:
    """``delete`` ops for our own playlists whose disks move (or are gone); ``skip`` notes
    for user playlists whose disks move."""
    from . import m3u  # local import: m3u imports this module

    moving = {_fold(op.src) for op in ops if op.status in MOVE_STATUSES}
    out: list[RenameOp] = []
    for path in m3u.find_m3us(root):
        info = m3u.read_m3u(path)
        if info is None:
            continue
        own, entries = info
        hits = [e for e in entries if _fold(e) in moving]
        if own:
            if hits:
                out.append(RenameOp(path, path, DELETE_STATUS,
                                    f"playlist made by this app; {len(hits)} of its disks move - "
                                    "write the M3Us again afterwards", "", "m3u"))
            elif entries and not any(_exists(e) for e in entries):
                out.append(RenameOp(path, path, DELETE_STATUS,
                                    "stale playlist made by this app (its disks are gone)", "", "m3u"))
        elif hits:
            out.append(RenameOp(path, path, "skip",
                                f"your playlist: {len(hits)} of its disks move - update it afterwards",
                                "", "m3u"))
    return out


def plan_counts(ops: Iterable[RenameOp]) -> dict[str, int]:
    """Counts by status plus ``to_unmatched`` (files that will move into ``_unmatched/``) and
    ``to_excluded`` / ``to_superseded`` / ``to_duplicates`` / ``to_incomplete`` (files moving into
    that reason folder; separate folders since Amendment 9)."""
    out: dict[str, int] = {}
    for op in ops:
        out[op.status] = out.get(op.status, 0) + 1
        if op.unmatched and op.status in MOVE_STATUSES:
            if op.code in CODE_DIRS:
                k = {"duplicate": "to_duplicates"}.get(op.code, f"to_{op.code}")
                out[k] = out.get(k, 0) + 1
            elif op.folder in ("", UNMATCHED_DIR):
                out["to_unmatched"] = out.get("to_unmatched", 0) + 1
    for k in ("to_unmatched", "to_excluded", "to_superseded", "to_duplicates", "to_incomplete"):
        out.setdefault(k, 0)
    return out


def reason_counts(plan: "LibraryPlan") -> dict[str, int]:
    """Preview cards of a :class:`LibraryPlan`: ``kept`` (matched files that end up in their canonical
    place, ``renamed`` / ``moved`` = of those, the ones that change), ``excluded`` / ``superseded`` /
    ``incomplete`` / ``duplicates`` (files moving there), ``unmatched`` (no-match files moving into
    ``_unmatched/``), ``conflict``, ``skip`` and the playlists (``playlists_write`` / ``_ok`` /
    ``_remove`` / ``_conflict``). ``excluded_<code>`` splits ``excluded`` by each file's PRIMARY reason
    (``bad_dump`` ... ``modified``, ``flag_cr`` ... ``flag_tr``, ``language``; always present, sums to
    ``excluded``)."""
    from . import bios, library

    out = dict.fromkeys(("kept", "renamed", "moved", "excluded", "superseded", "incomplete", "duplicates", "bios",
                         "unmatched", "saves", "conflict", "skip", "playlists_write", "playlists_ok",
                         "playlists_remove", "playlists_conflict"), 0)
    out.update(dict.fromkeys((f"excluded_{c}" for c in library.ALL_CODES), 0))
    borrow = plan.selection.borrow_summary()
    out["borrowed_sets"], out["borrowed_disks"] = borrow["sets"], borrow["disks"]
    out["kept_saved"] = plan.selection.saved_kept()
    for op in plan.ops:
        if op.status == DELETE_STATUS:
            out["playlists_remove"] += 1
        elif getattr(op, "bios", False):
            out["bios"] += 1                             # (BIOS / firmware / key files: counted apart from the games that are kept)
        elif op.status in ("conflict", "skip"):
            out[op.status] += 1
        elif op.code:
            if op.status in MOVE_STATUSES:
                out["duplicates" if op.code == "duplicate" else op.code] += 1
                if op.code == "excluded":
                    key = f"excluded_{op.reasons[0]}" if op.reasons else "excluded_other"
                    out[key] = out.get(key, 0) + 1
        elif op.unmatched:
            if op.status in MOVE_STATUSES and op.folder == folders.SAVES_DIR:
                out["saves"] += 1                        # (a save lying in the ROM folder, set aside under its game)
            elif op.status in MOVE_STATUSES and op.folder in ("", UNMATCHED_DIR):
                out["unmatched"] += 1
        elif op.status in MOVE_STATUSES or op.status in ("ok", "duplicate"):
            if bios.is_firmware_dat(op.dat) and getattr(getattr(plan, "profile", None), "keep_bios", True):
                out["bios"] += 1                         # (a game of a "- Firmware" DAT: the Amiga's Kickstarts)
                continue
            out["kept"] += 1
            if op.status in MOVE_STATUSES:
                out["renamed" if op.kind == "rename" else "moved"] += 1
    for p in plan.playlists:
        key = f"playlists_{p.status}"
        if key in out:
            out[key] += 1
    return out


