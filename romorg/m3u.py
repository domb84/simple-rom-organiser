@dataclass
class M3UOp:
    path: Path
    lines: list[str]
    status: str  # write | ok | conflict | incomplete | stale
    reason: str = ""
    dat: str = ""
    notes: list[str] = field(default_factory=list)    # "disk 2 borrowed from the (DE) edition (...)" per borrowed disk


def _fold(p: Path) -> str:
    return os.path.normcase(str(p)).casefold()


def find_m3us(root: Path) -> list[Path]:
    """Every ``*.m3u`` under root (hidden files/dirs and symlinked dirs skipped), sorted."""
    out: list[Path] = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if not d.startswith(".")]
        for f in filenames:
            if f.lower().endswith(".m3u") and not f.startswith("."):
                out.append(Path(dirpath) / f)
    out.sort(key=lambda p: str(p).casefold())
    return out


def _read_text(path: Path) -> str:
    with open(path, encoding="utf-8-sig", errors="surrogateescape", newline="") as f:
        return f.read(1 << 20)  # playlists are tiny; never read a huge mislabelled file


def entry_paths(lines: Iterable[str], directory: Path) -> list[Path]:
    """Disk paths referenced by m3u ``lines`` (labels and ``#member`` selectors removed)."""
    out: list[Path] = []
    for line in lines:
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        path = line.split("|", 1)[0].strip()
        hash_at = path.find("#", 1)
        while hash_at > 0:  # archive.zip#member.adf -> archive.zip
            head = path[:hash_at]
            if os.path.splitext(head)[1].lower() in ARCHIVE_EXTS | UNSUPPORTED_ARCHIVE_EXTS:
                path = head
                break
            hash_at = path.find("#", hash_at + 1)
        if not path:
            continue
        p = Path(path)
        out.append(Path(os.path.normpath(p if p.is_absolute() else directory / p)))
    return out


def read_m3u(path: Path) -> Optional[tuple[bool, list[Path]]]:
    """(made by us?, referenced disk paths) for an m3u file, or None if unreadable."""
    try:
        text = _read_text(path)
    except OSError:
        return None
    lines = text.replace("\r\n", "\n").split("\n")
    return lines[:1] == [M3U_MARKER], entry_paths(lines, path.parent)


def read_own_m3u_text(path: Path) -> Optional[str]:
    """Full text of an m3u generated by this app, or None (not ours / unreadable)."""
    try:
        text = _read_text(path)
    except OSError:
        return None
    return text if text.replace("\r\n", "\n").split("\n")[:1] == [M3U_MARKER] else None


def _member_counts(result: "ScanResult") -> dict[str, int]:
    counts: dict[str, int] = {}
    for e in [m.entry for m in result.matched] + list(result.unmatched):
        if e.member is not None:
            p = str(_abs(e.path, result.root))
            counts[p] = counts.get(p, 0) + 1
    return counts


def _disk_line(entry: "Entry", directory: Path, root: Path, member_counts: dict[str, int]) -> str:
    path = _abs(entry.path, root)
    rel = os.path.relpath(path, directory).replace(os.sep, "/")
    if entry.member is not None and member_counts.get(str(path), 1) > 1:
        rel = f"{rel}#{entry.member}"
    if rel.startswith("#"):
        rel = "./" + rel
    return rel


def _content(lines: list[str]) -> str:
    return "\n".join(lines) + "\n"


def _existing_state(path: Path, lines: list[str]) -> tuple[str, str]:
    """(status, reason) of ``path`` relative to the content we would write."""
    if not path.exists():
        return "write", ""
    try:
        text = _read_text(path)
    except OSError as exc:
        return "conflict", f"cannot read existing m3u: {exc}"
    if text.replace("\r\n", "\n") == _content(lines):
        return "ok", "up to date"
    if text.splitlines()[:1] == [M3U_MARKER]:
        return "write", "updates m3u previously generated by simple-rom-organiser"
    return "conflict", "an m3u not created by simple-rom-organiser exists"


def _ambiguous_bases(result: "ScanResult") -> set[tuple[str, str]]:
    """(dat, title + dump flags) that stand for sets of different disk counts in the DAT."""
    totals: dict[tuple[str, str], set[int]] = {}
    seen: set[tuple[str, str]] = set()
    for rom in list(result.missing) + [r for m in result.matched for r in m.roms]:
        k = (getattr(rom, "dat", ""), rom.name)
        if k in seen:
            continue
        seen.add(k)
        d = parse_disk_name(rom.name)
        if d is not None:
            totals.setdefault((k[0], d.title + "".join(_dump_flags(d.flags))), set()).add(d.total)
    return {k for k, v in totals.items() if len(v) > 1}


def plan_m3us(result: "ScanResult", savedisk: bool = False, labels: bool = True,
              dats: Optional[Collection[str]] = None,
              exclude_rules: Optional[Collection[str]] = None) -> list[M3UOp]:
    """Plan one m3u per multi-disk set (next to disk 1). Incomplete sets are reported, not written.

    ``dats``: only sets from these DATs (pass ``platform.m3u_dats``); None = all.
    ``exclude_rules``: exclusion rules (default all ``tags.RULES``) whose roms are never used.
    Our own playlists elsewhere under root that went stale are reported as ``stale``.
    """
    member_counts = _member_counts(result)
    sets = group_disk_sets(result, dats, exclude_rules)
    ambiguous = _ambiguous_bases(result)

    # Names: complete sets claim theirs first; incomplete sets never reserve one.
    used: set[str] = set()
    names: dict[int, Path] = {}
    for ds in sorted(sets, key=lambda s: not s.complete):
        suffix = f" ({ds.total} disks)" if (ds.dat, ds.base) in ambiguous else ""
        key = ds.key + suffix
        path = ds.directory / safe_filename(key + ".m3u")
        if _fold(path) in used and ds.full_key and ds.full_key != ds.key:
            # sets that differ only by a per-disk note: name them with all their flags
            path = ds.directory / safe_filename(ds.full_key + suffix + ".m3u")
        n = 2
        while _fold(path) in used:
            path = ds.directory / safe_filename(f"{key} ({n}).m3u")
            n += 1
        if ds.complete:
            used.add(_fold(path))
        names[id(ds)] = path

    ops: list[M3UOp] = []
    for ds in sets:
        path = names[id(ds)]
        if not ds.complete:
            reason = "missing disk " + ", ".join(str(i) for i in ds.missing)
            ops.append(M3UOp(path, [], "incomplete", f"{reason} ({ds.note})" if ds.note else reason, ds.dat))
            continue

        lines = [M3U_MARKER]
        bad: list[str] = []
        for i, match in ds.disks.items():
            line = _disk_line(match.entry, ds.directory, result.root, member_counts)
            if "|" in line or line != line.strip() or "\n" in line or "\r" in line:
                bad.append(line)
            if labels:
                label = (ds.labels.get(i) or f"Disk {i}").replace("\n", " ").strip()
                line = f"{line}|{label}"
            lines.append(line)
        if savedisk:
            lines.append("#SAVEDISK:")
        if bad:
            ops.append(M3UOp(path, lines, "conflict",
                             "filename can't be used in an m3u (contains '|' or edge spaces): "
                             + bad[0] + "; run organise first", ds.dat))
            continue
        status, reason = _existing_state(path, lines)
        extras = [reason, ds.note]
        if ds.total > PUAE_MAX_DISKS:
            extras.append(f"PUAE only loads the first {PUAE_MAX_DISKS} disks")
        ops.append(M3UOp(path, lines, status, ", ".join(x for x in extras if x), ds.dat))
    ops.extend(_stale_ops(result.root, ops))
    return ops


def _stale_ops(root: Path, ops: list[M3UOp], moving: Collection[str] = ()) -> list[M3UOp]:
    """Our playlists not in the plan that point at missing (or moving) files or duplicate a planned one."""
    moving_set = {_fold(Path(p)) for p in moving}
    planned = {_fold(op.path) for op in ops}
    planned_sets = {frozenset(_fold(p) for p in entry_paths(op.lines, op.path.parent)): op.path
                    for op in ops if op.status in ("write", "ok")}
    out: list[M3UOp] = []
    try:
        found = find_m3us(root)
    except OSError:
        return out
    for path in found:
        if _fold(path) in planned:
            continue
        info = read_m3u(path)
        if info is None or not info[0]:
            continue
        entries = info[1]
        missing = [e for e in entries if not os.path.lexists(e) or _fold(e) in moving_set]
        twin = planned_sets.get(frozenset(_fold(e) for e in entries))
        if missing:
            out.append(M3UOp(path, [], "stale", f"made by this app; {len(missing)} of its disks no longer "
                                                "exist at that place - it will be removed"))
        elif twin is not None and entries:
            out.append(M3UOp(path, [], "stale", f"made by this app; replaced by {twin.name} - it will be removed"))
    return out


def _write_new(path: Path, text: str) -> None:
    """Write via a unique temp file in the same folder, then replace ``path``."""
    tmp = path.with_name(f".{path.name}{TEMP_MARKER}{uuid.uuid4().hex[:8]}")
    try:
        with open(tmp, "x", encoding="utf-8", errors="surrogateescape", newline="\n") as f:
            f.write(text)
        os.replace(tmp, path)
    finally:
        if os.path.lexists(tmp):
            try:
                os.unlink(tmp)
            except OSError:
                pass


def write_m3us(ops: Iterable[M3UOp]) -> dict:
    """Write the ``write`` ops and remove the ``stale`` ones (re-checking ownership first).

    Returns ``{"written", "removed", "failed": [{"path", "error"}], "skipped"}``.
    """
    written = skipped = removed = 0
    failed: list[dict[str, str]] = []
    for op in ops:
        if op.status == "stale":
            info = read_m3u(op.path)
            if info is None or not info[0]:
                skipped += 1
                continue
            try:
                os.unlink(op.path)
                removed += 1
            except OSError as exc:
                failed.append({"path": str(op.path), "error": str(exc)})
            continue
        if op.status != "write":
            skipped += 1
            continue
        status, reason = _existing_state(op.path, op.lines)
        if status == "ok":
            skipped += 1
            continue
        if status != "write":
            failed.append({"path": str(op.path), "error": reason})
            continue
        try:
            _write_new(op.path, _content(op.lines))
            written += 1
        except (OSError, UnicodeError) as exc:
            failed.append({"path": str(op.path), "error": str(exc)})
    return {"written": written, "removed": removed, "failed": failed, "skipped": skipped}



# --------------------------------------------------------------------------- library playlists


@dataclass
class PlaylistDisk:
    slot: int
    path: Path               # FINAL location of the disk file
    member: Optional[str]    # archive member, if the disk lives inside a zip/7z
    label: str = ""


@dataclass
class PlaylistSpec:
    name: str                # file stem (no ".m3u")
    dat: str
    total: int
    disks: list[PlaylistDisk]
    notes: list[str] = field(default_factory=list)    # one line per disk borrowed from another edition


def content_of(lines: list[str]) -> str:
    return _content(lines)


def plan_playlists(specs: Iterable[PlaylistSpec], root: Path, savedisk: bool = False, labels: bool = True,
                   member_counts: Optional[Mapping[str, int]] = None) -> list[M3UOp]:
    """One playlist per spec, next to the lowest slot's disk. Status write | ok | conflict.

    Name collisions (case-insensitive, same folder) get `` (2)``, `` (3)`` ... in spec order.
    """
    counts = member_counts or {}
    used: set[str] = set()
    ops: list[M3UOp] = []
    for spec in specs:
        disks = sorted(spec.disks, key=lambda d: d.slot)
        if not disks:
            continue
        directory = _abs(disks[0].path, root).parent
        path = directory / safe_filename(spec.name + ".m3u")
        n = 2
        while _fold(path) in used:
            path = directory / safe_filename(f"{spec.name} ({n}).m3u")
            n += 1
        used.add(_fold(path))
        lines = [M3U_MARKER]
        bad: list[str] = []
        for d in disks:
            full = _abs(d.path, root)
            rel = os.path.relpath(full, directory).replace(os.sep, "/")
            if d.member is not None and counts.get(str(full), 1) > 1:
                rel = f"{rel}#{d.member}"
            if rel.startswith("#"):
                rel = "./" + rel
            if "|" in rel or rel != rel.strip() or "\n" in rel or "\r" in rel:
                bad.append(rel)
            if d.member is not None and os.path.splitext(str(full))[1].lower() not in ARCHIVE_EXTS:
                bad.append(rel)
            line = rel
            if labels:
                line = f"{rel}|{(d.label or f'Disk {d.slot}').replace(chr(10), ' ').strip()}"
            lines.append(line)
        if savedisk:
            lines.append("#SAVEDISK:")
        if bad:
            ops.append(M3UOp(path, lines, "conflict",
                             "filename can't be used in an m3u (contains '|', edge spaces or an "
                             "unsupported archive): " + bad[0], spec.dat))
            continue
        status, reason = _existing_state(path, lines)
        extras = [reason]
        if spec.total > PUAE_MAX_DISKS:
            extras.append(f"PUAE only loads the first {PUAE_MAX_DISKS} disks")
        ops.append(M3UOp(path, lines, status, ", ".join(x for x in extras if x), spec.dat, list(spec.notes)))
    return ops


def plan_stale(root: Path, planned: list[M3UOp], moving: Collection[str] = ()) -> list[M3UOp]:
    """Our own playlists not in ``planned`` whose disks are gone, about to move (``moving`` =
    absolute disk paths) or that a planned playlist replaces; status ``stale``."""
    return _stale_ops(root, planned, moving)


def write_playlist(path: Path, text: str, replace_own: bool = False) -> tuple[str, int]:
    """Write a playlist atomically; returns (sha1, size). Raises FileExistsError unless the
    target is absent or (``replace_own``) one of our own playlists."""
    import hashlib
    data = text.encode("utf-8", errors="surrogateescape")
    if os.path.lexists(path):
        if not replace_own or read_own_m3u_text(path) is None:
            raise FileExistsError(str(path))
    tmp = path.with_name(f".{path.name}{TEMP_MARKER}{uuid.uuid4().hex[:8]}")
    try:
        with open(tmp, "xb") as f:
            f.write(data)
        if replace_own:
            os.replace(tmp, path)
        else:
            try:
                os.link(tmp, path)  # fails with FileExistsError instead of overwriting
            except FileExistsError:
                raise
            except (OSError, NotImplementedError, AttributeError):
                # FAT/exFAT have no hard links: check-then-rename.
                if os.path.lexists(path):
                    raise FileExistsError(str(path)) from None
                os.rename(tmp, path)
    finally:
        if os.path.lexists(tmp):
            try:
                os.unlink(tmp)
            except OSError:
                pass
    return hashlib.sha1(data).hexdigest(), len(data)
