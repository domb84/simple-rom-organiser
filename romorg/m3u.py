ARCHIVE_EXTS = {".zip", ".7z"}           # what PUAE can open inside an m3u
UNSUPPORTED_ARCHIVE_EXTS = {".rar"}

_DISK_TOKEN = re.compile(
    r"\((?:Disk|Side) ([0-9]+|[A-Z]) of ([0-9]+|[A-Z])\)((?:\([^()]*\))*)"
)
_PAREN = re.compile(r"\(([^()]*)\)")
_FLAG = re.compile(r"\[[^\[\]]*\]")


# --------------------------------------------------------------------------- parsing


def _to_number(token: str) -> int:
    return int(token) if token.isdigit() else ord(token) - ord("A") + 1


@dataclass(frozen=True)
class DiskName:
    """A TOSEC rom name split into its multi-disk parts."""

    title: str               # name minus disk token, labels and flags
    index: int
    total: int
    label: str               # media label(s) after the token, "" if none
    flags: tuple[str, ...]   # "[...]" groups in order


def parse_disk_name(name: str) -> Optional[DiskName]:
    """Parse ``name`` (with or without extension); None if it has no disk token."""
    stem = name
    dot = stem.rfind(".")
    if dot > 0 and " " not in stem[dot:] and len(stem) - dot <= 5:
        stem = stem[:dot]
    m = _DISK_TOKEN.search(stem)
    if not m:
        return None
    index, total = _to_number(m.group(1)), _to_number(m.group(2))
    if total < 2 or index < 1:
        return None
    label = " - ".join(p.strip() for p in _PAREN.findall(m.group(3)) if p.strip())
    rest = stem[m.end():]
    flags = tuple(_FLAG.findall(rest))
    title = (stem[: m.start()].rstrip() + _FLAG.sub("", rest)).strip()
    return DiskName(title=title, index=index, total=total, label=label, flags=flags)


# --------------------------------------------------------------------------- grouping


@dataclass
class DiskSet:
    key: str
    total: int
    disks: dict[int, "Match"]
    missing: list[int]
    directory: Path
    labels: dict[int, str] = field(default_factory=dict)
    roms: dict[int, "Rom"] = field(default_factory=dict)
    flags: tuple[str, ...] = ()
    dat: str = ""  # sets never span DATs
    note: str = ""  # why the set is what it is (informational)
    base: str = ""  # title + dump flags (used to detect names shared by several totals)
    full_key: str = ""  # title + every flag of the anchor (fallback name on a collision)

    @property
    def complete(self) -> bool:
        return not self.missing and len(self.disks) == self.total


@dataclass(frozen=True)
class DiskCand:
    """One local disk that may fill a slot. ``ref`` is the caller's handle (opaque to us)."""

    ref: Any
    name: str  # TOSEC rom name (with or without extension)


@dataclass
class SlotSet:
    """One playlist-to-be: for every disk slot the newest compatible disk the user has."""

    identity: tuple
    total: int
    anchor: Optional[DiskCand]      # the disk 1 the set is built around (None: no disk 1 at all)
    slots: dict[int, DiskCand]
    missing: list[int]
    flags: tuple[str, ...]
    labels: dict[int, str]
    name: str
    note: str = ""
    title: str = ""                 # anchor title (name minus disk token, labels and flags)

    @property
    def complete(self) -> bool:
        return not self.missing and len(self.slots) == self.total


def _abs(path: Path, root: Path) -> Path:
    return path if path.is_absolute() else root / path


def _usable(entry: "Entry") -> bool:
    if entry.member is None:
        return True
    ext = entry.path.suffix.lower()
    return ext in ARCHIVE_EXTS and ext not in UNSUPPORTED_ARCHIVE_EXTS


# Standard TOSEC dump-flag codes ([cr], [t +2], [a2], [b dump] ...). Any other
# bracketed note ([!], [bootable], [cp manual code], [docs], [HD], [1Mb Chip] ...)
# describes one disk and does not make it incompatible with the rest of a set,
# except notes that mark a different build ([beta 3], [AGA version] ...).
_DUMP_FLAG = re.compile(r"^\[(?:cr|f|h|m|p|t|tr|o|u|v|b|a)\d*(?:[ \]])")
_BUILD_NOTE = re.compile(r"^\[(?:beta|alpha|proto(?:type)?|preview|pre-release|demo|compilation)\b|version\]$",
                         re.IGNORECASE)
_BARE_CODE = re.compile(r"^([a-z]+)\d*$")
_CODE_WITH_TEXT = re.compile(r"^([a-z]+)\d* ")


def is_neutral_flag(flag: str) -> bool:
    """True for informational flags that don't distinguish dump variants."""
    return not _DUMP_FLAG.match(flag) and not _BUILD_NOTE.search(flag)


def generalises(flag: str, other: str) -> bool:
    """True when dump flag ``flag`` is a bare/shorter form of ``other`` (same code).

    ``[cr]`` / ``[cr2]`` generalise ``[cr CSL]``; ``[cr Galahad]`` generalises
    ``[cr Galahad v1]``; ``[h PDX]`` generalises ``[h PDX - RSi]``. ``[a]`` does not
    generalise ``[a2]`` (different alternates).
    """
    c, v = flag[1:-1], other[1:-1]
    if c == v:
        return False
    if v.startswith(c + " "):
        return True
    bare = _BARE_CODE.match(c)
    if bare:
        code = _CODE_WITH_TEXT.match(v)
        return code is not None and code.group(1) == bare.group(1)
    return False


def _compat(flags: Iterable[str], variant: frozenset[str]) -> Optional[tuple[int, int, int]]:
    """(generalised, -shared, extra neutral) if a disk with ``flags`` fits ``variant``, else None."""
    fs = frozenset(flags)
    general = neutral = 0
    for f in fs - variant:
        if is_neutral_flag(f):
            neutral += 1
        elif any(generalises(f, v) for v in variant):
            general += 1
        else:
            return None
    return general, -len(fs & variant), neutral


def _dump_flags(flags: Iterable[str]) -> tuple[str, ...]:
    return tuple(f for f in flags if not is_neutral_flag(f))


# --- helpers that prefer tags.py's public API (amendment 6) and degrade gracefully

_DATE_PAREN = re.compile(r"\((?:[0-9x?]{4})(?:-[0-9x?]{2}(?:-[0-9x?]{2})?)?\)", re.IGNORECASE)


def _date_key(date: str) -> str:
    fn = getattr(_tags, "date_key", None)
    return fn(date) if fn else (date or "").replace("x", "0").replace("X", "0").replace("?", "0")


def _version_keys(names: list[str]) -> dict[str, tuple]:
    fn = getattr(_tags, "group_version_keys", None)
    if fn is not None:
        return fn(names, _tags.STYLE_TOSEC)
    return _tags._group_keys(names, _tags.STYLE_TOSEC)


def identity_of(name: str) -> tuple:
    """Game identity of a TOSEC rom name: same product regardless of version, date, disk, flags."""
    d = parse_disk_name(name)
    if d is not None:  # drop the disk token + labels so none of it is mistaken for a publisher
        name = d.title + "".join(d.flags)
    t = _tags.parse_name(name, _tags.STYLE_TOSEC)
    fn = getattr(_tags, "identity_key", None)
    if fn is not None:
        return fn(t)
    title = d.title if d else name
    if t.version:
        title = title.replace(t.version, "", 1)
    title = _DATE_PAREN.sub("", title)
    return (t.style, re.sub(r"\s+", " ", title).strip().casefold(), t.regions,
            () if t.languages_implied else t.languages)


_FALLBACK_RULES = {
    "bad_dump": re.compile(r"^b\d*(\s.*)?$"), "virus": re.compile(r"^v\d*(\s.*)?$"),
    "bad_size": re.compile(r"^[ou]\d*(\s.*)?$"), "modified": re.compile(r"^m\d*(\s.*)?$|^modified\b"),
    "faked": re.compile(r"^fake(d)?\b"), "unreleased": re.compile(r"^unreleased\b"),
}
_FALLBACK_PAREN = {"beta": "pre_release", "alpha": "pre_release", "preview": "pre_release",
                   "pre-release": "pre_release", "proto": "prototype", "unreleased": "unreleased",
                   "demo": "demo"}


def excluded_rules(name: str) -> frozenset[str]:
    """Exclusion rules (``tags.RULES`` keys) a rom name falls under."""
    t = _tags.parse_name(name, _tags.STYLE_TOSEC)
    fn = getattr(_tags, "exclusion_rules", None)
    if fn is not None:
        return fn(t)
    out: set[str] = set()
    for f in t.dump_flags:
        body = f[1:-1]
        for rule, rx in _FALLBACK_RULES.items():
            if rx.match(body):
                out.add(rule)
    for p in ([t.status] if t.status else []) + [x[1:-1] for x in t.flags if x.startswith("(")]:
        word = re.sub(r"\s+\d+$", "", p.casefold())
        if word.startswith("demo"):
            out.add("demo")
        elif word in _FALLBACK_PAREN:
            out.add(_FALLBACK_PAREN[word])
    return frozenset(out)


def _all_rules() -> frozenset[str]:
    return frozenset(getattr(_tags, "RULES", ("bad_dump", "virus", "bad_size", "pre_release", "prototype",
                                               "demo", "faked", "unreleased", "modified")))


# --------------------------------------------------------------------------- slot resolution


@dataclass
class _P:
    idx: int
    cand: DiskCand
    disk: DiskName
    vkey: tuple
    date: str


def _newest_first(p: _P) -> tuple:
    return (p.vkey, p.date)


def _pick_slot(options: list[_P], fset: frozenset[str], limit: Optional[tuple] = None) -> Optional[_P]:
    """Newest compatible disk for the slot (not newer than ``limit``); ties broken by exact
    flags, shared flags, then name."""
    ranked: list[tuple[tuple, _P]] = []
    for p in options:
        if limit is not None and p.vkey > limit:
            continue
        rank = _compat(p.disk.flags, fset)
        if rank is None:
            continue
        verified = 0 if "[!]" in p.disk.flags else 1      # a verified good dump wins a tie
        ranked.append(((rank[0], verified, *rank[1:], len(p.cand.name), p.cand.name, p.idx), p))
    ranked.sort(key=lambda kp: kp[0])
    best: Optional[_P] = None
    for _, p in ranked:
        if best is None or _newest_first(p) > _newest_first(best):
            best = p
    return best


def pick_borrowed(options: Sequence[DiskCand], anchor_flags: Iterable[str], vkeys: Mapping[str, tuple],
                  tier: Optional[Any] = None) -> Optional[DiskCand]:
    """The disk of ANOTHER edition that fills a slot (``borrow_other_editions``, Amendment 12).

    ``options`` = disks (all of the same slot number and disk total) the caller found eligible: same title,
    publisher and total, no quality exclusion, compatible chipset. The disk must still fit the anchor's dump
    flags (:func:`_compat`: a different crack, ``[t ..]``, ``[h ..]`` never fits; a bare disk fits any
    ``[cr X]``). ``tier(cand)`` ranks candidate groups, lowest first (same edition / selected language /
    any other); within a tier the newest ``(version, date)`` wins, ties by the crack-compatibility order of
    :func:`_pick_slot` (``vkeys`` only ranks - a borrowed disk may be newer than the anchor)."""
    fset = frozenset(anchor_flags)
    ps: list[_P] = []
    for i, c in enumerate(options):
        d = parse_disk_name(c.name)
        if d is None:
            continue
        date = _date_key(_tags.parse_name(c.name, _tags.STYLE_TOSEC).date)
        ps.append(_P(i, c, d, vkeys.get(c.name, (0,)), date))
    ranks = sorted({(tier(p.cand) if tier else 0) for p in ps})
    for r in ranks:
        best = _pick_slot([p for p in ps if (tier(p.cand) if tier else 0) == r], fset, None)
        if best is not None:
            return best.cand
    return None


def _slot_name(title: str, flags: tuple[str, ...], chosen: Collection[DiskName]) -> str:
    shared = [f for f in flags if not is_neutral_flag(f) or all(f in d.flags for d in chosen)]
    return title + "".join(shared)


def resolve_slots(cands: Sequence[DiskCand], vkeys: Optional[Mapping[str, tuple]] = None) -> list[SlotSet]:
    """Slot-wise multi-disk sets for the candidates of ONE game identity.

    Disks never mix across languages or chipsets (``tags.partition_key``: explicit language tags and
    ``AGA`` / ``OCS-AGA`` ... tags, which are no longer part of the identity): each partition is
    resolved on its own and the sets are merged.
    """
    parts: dict[tuple, list[DiskCand]] = {}
    for c in cands:
        parts.setdefault(_tags.partition_key(_tags.parse_name(c.name, _tags.STYLE_TOSEC)), []).append(c)
    if len(parts) <= 1:
        return _resolve_partition(cands, vkeys)
    out: list[SlotSet] = []
    for key in sorted(parts, key=repr):
        out.extend(_resolve_partition(parts[key], vkeys))
    out.sort(key=lambda s: (s.total, s.name.casefold(), s.name))
    return out


def _resolve_partition(cands: Sequence[DiskCand], vkeys: Optional[Mapping[str, tuple]] = None) -> list[SlotSet]:
    """:func:`resolve_slots` for candidates of one language / chipset partition.

    TOSEC only lists the disks that changed between versions, so ``X v1.1 (Disk 1 of 3)[cr SR]``
    goes with ``X (1990) (Disk 2 of 3)``: for every anchor (a disk 1) each slot takes the newest
    compatible disk that is not newer than the anchor. Callers pass only eligible disks
    (no excluded / bad variants). Incomplete sets are returned too (``missing`` lists the slots).
    """
    parsed: list[_P] = []
    names = [c.name for c in cands]
    keys = dict(vkeys) if vkeys is not None else _version_keys(names)
    for i, c in enumerate(cands):
        d = parse_disk_name(c.name)
        if d is None:
            continue
        if c.name not in keys:
            keys.update(_version_keys(names))
        date = _date_key(_tags.parse_name(c.name, _tags.STYLE_TOSEC).date)
        parsed.append(_P(i, c, d, keys.get(c.name, (0,)), date))

    by_total: dict[int, dict[int, list[_P]]] = {}
    for p in parsed:
        by_total.setdefault(p.disk.total, {}).setdefault(p.disk.index, []).append(p)

    built: list[tuple[frozenset, SlotSet, Optional[_P]]] = []
    for total in sorted(by_total):
        by_index = by_total[total]
        anchors = sorted(by_index.get(1, []), key=lambda p: (p.cand.name, p.idx))
        # (disk 1 or None, flag set the other slots must fit)
        plans: list[tuple[Optional[_P], frozenset[str], _P]] = [(a, frozenset(a.disk.flags), a) for a in anchors]
        pool = sorted((p for ps in by_index.values() for p in ps), key=lambda p: (p.cand.name, p.idx))
        if not anchors:
            newest = max(pool, key=lambda p: (_newest_first(p), -len(p.cand.name), p.cand.name))
            plans.append((None, frozenset(newest.disk.flags), newest))
        else:
            # Flag sets only some other disk carries (a trainer on disk 2 only): disk 1 is then
            # the newest one compatible with that flag set.
            known = {f for _, f, _ in plans}
            for p in pool:
                f = frozenset(p.disk.flags)
                if f in known:
                    continue
                known.add(f)
                d1 = _pick_slot(by_index[1], f)
                if d1 is not None:
                    plans.append((d1, f, p))
        for real, fset, ref in plans:
            chosen: dict[int, _P] = {}
            if real is not None:
                chosen[1] = real
            else:
                chosen[ref.disk.index] = ref
            for i in range(1, total + 1):
                if i not in chosen:
                    p = _pick_slot(by_index.get(i, []), fset, (real or ref).vkey)
                    if p is not None:
                        chosen[i] = p
            sel = frozenset((i, p.idx) for i, p in chosen.items())
            head = real or ref
            flags = ref.disk.flags
            ss = SlotSet(
                identity=(), total=total, anchor=real.cand if real else None,
                slots={i: p.cand for i, p in sorted(chosen.items())},
                missing=[i for i in range(1, total + 1) if i not in chosen],
                flags=flags, labels={i: p.disk.label for i, p in sorted(chosen.items())},
                name=_slot_name(head.disk.title, flags, [p.disk for p in chosen.values()]),
                note="" if real else "no disk 1 in the set", title=head.disk.title,
            )
            built.append((sel, ss, real))

    out: list[SlotSet] = []
    seen: set[frozenset] = set()
    for sel, ss, _ in built:
        if sel in seen:
            continue
        seen.add(sel)
        if not ss.complete and any(o != sel and sel < o for o, _, _ in built):
            continue
        out.append(ss)
    out.sort(key=lambda s: (s.total, s.name.casefold(), s.name))
    return out


@dataclass
class _Local:
    match: "Match"
    rom: "Rom"
    ident: tuple[str, str]


def group_disk_sets(result: "ScanResult", dats: Optional[Collection[str]] = None,
                    exclude_rules: Optional[Collection[str]] = None) -> list[DiskSet]:
    """All multi-disk sets (total >= 2) found among the matched files, sorted by key.

    ``dats`` restricts grouping to those DAT names (e.g. ``platform.m3u_dats``);
    None means every DAT. Sets are grouped per (DAT, game identity) and never span DATs.
    ``exclude_rules`` (default: all ``tags.RULES``) are the exclusion rules whose roms are
    never part of a set (bad dumps, pre-releases, ...).
    """
    rules = _all_rules() if exclude_rules is None else frozenset(exclude_rules)
    groups: dict[tuple[str, tuple], list[DiskCand]] = {}
    seen: set[tuple] = set()
    for m in result.matched:
        e = m.entry
        if not _usable(e):
            continue
        ident = (str(_abs(e.path, result.root)), e.member or "")
        for rom in m.primary:
            if dats is not None and rom.dat not in dats:
                continue
            if parse_disk_name(rom.name) is None:
                continue
            k = (ident, rom.dat, rom.name)
            if k in seen:
                continue
            seen.add(k)
            if rules and excluded_rules(rom.name) & rules:
                continue
            groups.setdefault((rom.dat, identity_of(rom.name)), []).append(
                DiskCand(_Local(m, rom, ident), rom.name))

    sets: list[DiskSet] = []
    for (dat, identity), cands in groups.items():
        found = resolve_slots(cands)
        for ss in found:
            # Incomplete variants of a game that has a complete set (same disk count) are noise.
            if not ss.complete and any(o.complete and o.total == ss.total for o in found):
                continue
            slots = {i: c.ref for i, c in ss.slots.items()}
            first = slots[min(slots)]
            sets.append(DiskSet(
                key=ss.name, total=ss.total,
                disks={i: r.match for i, r in slots.items()},
                missing=list(ss.missing),
                directory=_abs(first.match.entry.path, result.root).parent,
                labels=dict(ss.labels), roms={i: r.rom for i, r in slots.items()},
                flags=ss.flags, dat=dat, note=ss.note,
                base=ss.title + "".join(_dump_flags(ss.flags)),
                full_key=ss.title + "".join(ss.flags),
            ))
    sets.sort(key=lambda s: (s.key.lower(), s.total, s.dat))
    return sets


