"""Group multi-disk sets and plan/write M3U playlists for the libretro PUAE core.

PUAE m3u format (verified against https://docs.libretro.com/library/puae/ and the
parser ``dc_parse_m3u`` in libretro-uae ``libretro/libretro-dc.c``):

* Plain text, one disk per line, in disk-control order. Paths may be absolute or
  relative to the m3u's directory. Each line is whitespace-trimmed, so names
  with leading/trailing spaces can't be referenced.
* ``#SAVEDISK:<VolumeName>`` adds a blank save disk (volume name optional).
* ``#COMMAND:`` is special; every other line starting with ``#`` is ignored, so
  our first-line ownership marker ``# Generated by simple-rom-organiser`` is safe.
  A disk path that itself starts with ``#`` is written as ``./#...``.
* ``path|Label`` sets the disk-control label; the split is at the *first* ``|``,
  so paths containing ``|`` can't be referenced (``safe_filename`` removes them).
* ``archive.zip#member.adf`` / ``.7z#`` selects one disk in a multi-file archive;
  single-file archives can be referenced directly. ``.rar`` is not supported.
* PUAE loads at most 20 entries (``DC_MAX_SIZE``).

TOSEC multi-disk naming (as found in "Commodore Amiga - Games - [ADF]"
TOSEC-v2025-01-30, 34410 roms, 19183 carrying a disk token)::

    Title (Year)(Publisher)[(other)](Disk X of Y)[(label)...][flags]

* The only disk token form in that DAT is ``(Disk N of M)``; ``(Disk A of B)``
  letters and ``(Side X of Y)`` are accepted as well. A bare ``(Disk 1)`` without
  a total never appears as the media token (only as a *label*, e.g.
  ``(Disk 2 of 3)(Disk1)``), so it is not treated as one.
* Zero or more ``(...)`` groups directly after the token are the per-disk media
  label (``(Boot)``, ``(Program)``, ``(Data Disk)``, ``(A)``, ``(Reel 1)``, ``(Disk1)``
  ...). They are removed from the grouping key and used as the m3u label.
* Dump flags ``[...]`` are **per disk**: a trainer, bad dump or hack usually only
  touches the disk it modified, e.g. ``X (Disk 1 of 2)[cr CSL][t +12 GOD]`` goes
  with ``X (Disk 2 of 2)[cr CSL]``. Grouping on the full name (flags included)
  completes only ~14% of the real DAT's sets, and TOSEC lists only the disks that
  changed between versions, so sets are built *slot by slot* (:func:`resolve_slots`):

  1. Candidates are grouped by game *identity* (``tags.identity_key``: title without
     version/date, publisher, region, language, edition), so versions of one game share a group.
  2. Every disk 1 is an *anchor* with flag set ``F``. For each slot ``i`` the set takes the
     newest disk ``i`` the user has that is compatible with ``F`` and not newer than the anchor.
     ``ABC Monday Night Football v1.1 (1991)(Data East)(US)(Disk 1 of 3)[cr SR]`` therefore
     gets ``... (1990)(Data East)(US)(Disk 2 of 3)`` and ``(Disk 3 of 3)``, which carry no version.
     Dump flags ``[cr ..]``, ``[t ..]``, ``[h ..]``, ``[a]``, ``[b ..]`` ... outside ``F`` make a
     disk incompatible (different cracks are never mixed) unless they *generalise* a flag of
     ``F`` (``[cr]`` / ``[cr Galahad]`` go with ``[cr CSL]`` / ``[cr Galahad v1]``); notes such
     as ``[!]``, ``[bootable]``, ``[cp manual code]``, ``[docs]``, ``[HD]`` are neutral.
  3. Callers pass only eligible disks: excluded variants (pre-release, bad dumps, ...) are
     never borrowed from.

  Sets that select the same files are merged, incomplete sets contained in another set are
  dropped, a group without any disk 1 yields one incomplete pseudo-set. There are no
  best-effort sets: a set is complete only when every slot 1..N is filled.
* M3U name = anchor title + the anchor's dump flags + the neutral flags shared
  by every chosen disk, e.g. ``ABC Monday Night Football v1.1 (1991)(Data East)(US)[cr SR].m3u``
  or ``'Allo 'Allo! Cartoon Fun! (1993)(Alternative)[cr CSL][t +12 GOD].m3u``. When the
  same name stands for sets with different disk counts in the DAT, ``(N disks)`` is
  always appended, so a name never depends on which other files are present.
  Names are compared case-insensitively (exFAT SD cards).
* Our own playlists that are no longer part of the plan and point at missing
  files, or duplicate a planned playlist, are reported as ``stale`` and removed
  by :func:`write_m3us`.
"""

